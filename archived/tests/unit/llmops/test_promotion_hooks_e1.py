"""Tests for the 4 missing §E.1 PromotionHook methods (Phase 2
cross-cutting — wire up the compliance_gap + sla_breach hooks
that the spec's hook taxonomy expects).

Per spec §E.1:

* ``on_compliance_gap_soc2`` — high, Alert → Investigation
  (added 2026-06-24)
* ``on_compliance_gap_gdpr`` — critical, Alert +
  Auto-RTBF suggestion (ACTION_KIND entry existed since
  2026-06-23 but the method was a stub until this commit;
  RTBF execution requires D.11 which is deferred per
  user — the hook still records the event so the
  operator can see the GDPR gap in the closed-loop
  dashboard)
* ``on_compliance_gap_hipaa`` — high, Alert
  (added 2026-06-24)
* ``on_compliance_gap_iso27001`` — high, Alert
  (added 2026-06-24)
* ``on_sla_breach`` — high, Alert → Investigation
  (ACTION_KIND entry existed since 2026-06-23 but the
  method was a stub until this commit)

The tests use the real :class:`HookBus` singleton — the
hook is wired end-to-end and the only assertion is that
the bus returns a non-empty ``hook_id`` (a UUID is
generated by the bus on emit).
"""

from __future__ import annotations

import pytest

from eden.llmops.promotion_hooks import PromotionHook


@pytest.fixture
def hook() -> PromotionHook:
    """Fresh :class:`PromotionHook` for each test."""
    return PromotionHook()


class TestComplianceGapHooks:
    """4 §E.1 compliance_gap hook tests."""

    async def test_on_compliance_gap_soc2_returns_hook_id(self, hook):
        action_id = await hook.on_compliance_gap_soc2(
            "org-1",
            finding_id="finding-1",
            framework_control="CC1.2",
        )
        assert action_id is not None
        assert isinstance(action_id, str)
        assert len(action_id) > 0

    async def test_on_compliance_gap_gdpr_returns_hook_id(self, hook):
        """The GDPR hook's ACTION_KIND entry is ``rtbf`` (per
        spec row 4: "Auto-RTBF suggestion"). D.11 cross-store
        is deferred (no legal team), so the rtbf side-effect
        is a no-op in v0 — the hook still records the event
        so the operator can see the GDPR gap in the
        closed-loop dashboard. The test asserts the
        hook_id is non-empty.
        """
        action_id = await hook.on_compliance_gap_gdpr(
            "org-1",
            finding_id="finding-gdpr-1",
            framework_control="Art.17",
            details={"subject_id": "user-42", "data_categories": ["trace_content"]},
        )
        assert action_id is not None
        assert isinstance(action_id, str)
        assert len(action_id) > 0

    async def test_on_compliance_gap_hipaa_returns_hook_id(self, hook):
        action_id = await hook.on_compliance_gap_hipaa(
            "org-1",
            finding_id="finding-hipaa-1",
            framework_control="164.312(a)(1)",
        )
        assert action_id is not None
        assert isinstance(action_id, str)

    async def test_on_compliance_gap_iso27001_returns_hook_id(self, hook):
        action_id = await hook.on_compliance_gap_iso27001(
            "org-1",
            finding_id="finding-iso-1",
            framework_control="A.9.4.1",
        )
        assert action_id is not None
        assert isinstance(action_id, str)


class TestSlaBreachHook:
    """1 §E.1 sla_breach hook test (per spec row 9, source Cat 16)."""

    async def test_on_sla_breach_returns_hook_id(self, hook):
        action_id = await hook.on_sla_breach(
            "org-1",
            sla_id="sla-compaction-4h",
            sla_name="columnar_compaction_4h",
            target_ms=4 * 60 * 60 * 1000,  # 4h in ms
            actual_ms=5 * 60 * 60 * 1000,  # 5h — 25% over
            breach_pct=0.25,
        )
        assert action_id is not None
        assert isinstance(action_id, str)
        assert len(action_id) > 0
