import { clerkMiddleware, createRouteMatcher } from "@clerk/nextjs/server";
import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";
import { KNOWN_PORTAL_PREFIXES } from "@/lib/portal-routes";
import { resolveHubTarget } from "@/lib/portal-hub-redirect";

// Protected-first: block everything, allow the routes that must stay
// reachable without a session (marketing pages, auth flows, and
// Clerk's own internal callbacks).
//
// /api/health is a public, unauthenticated health probe so uptime
// monitors and the auth-card status badge can call it without
// needing a Clerk session. Wave 4: ``/api/proxy/(.*)`` is NOT public —
// unauthenticated callers are redirected to sign-in. The route
// handler still forwards Clerk Bearer + session cookies once the
// middleware has confirmed a session.
const isPublicRoute = createRouteMatcher([
  "/",
  "/login(.*)",
  "/signup(.*)",
  "/forgot-password(.*)",
  "/reset-password(.*)",
  "/invite(.*)",
  // Marketing / legal pages — must be public so anonymous browsers
  // and search-engine crawlers can fetch them. Without this, the
  // Clerk middleware 404s them (which is a real bug the user
  // reported: "loads of 404, not found"). July 2026 fix.
  "/privacy(.*)",
  "/security(.*)",
  "/terms(.*)",
  "/dpa(.*)",
  "/pricing(.*)",
  "/about(.*)",
  "/contact(.*)",
  "/changelog(.*)",
  "/subprocessors(.*)",
  "/do-not-sell(.*)",
  // Public system status (marketing) — must not fall through to
  // portal catch-all / soft-404 “Loading” shells. `/health` aliases
  // `/status`; `/api/health` is the machine-readable probe.
  "/status(.*)",
  "/health(.*)",
  // SEO files — generated by Next.js (robots.ts, sitemap.ts) and
  // served as static. Must be public or crawlers get 404.
  "/robots.txt",
  "/sitemap.xml",
  // App Router OG / Twitter image special files (crawlers + link previews).
  "/opengraph-image",
  "/opengraph-image/(.*)",
  "/twitter-image",
  "/twitter-image/(.*)",
  "/og.png",
  "/og-pricing.png",
  "/icon(.*)",
  "/apple-icon(.*)",
  "/api/health",
  // Docs Fill-in (CORS from docs.edenobservability.com). Auth is
  // checked inside the handler via Clerk ``auth().getToken()``.
  "/api/docs",
  "/api/docs/(.*)",
  // ai-insights routes are pass-through proxies that forward the
  // request cookie + Clerk Bearer to FastAPI, which does its own
  // auth (returns 401 on bad/missing token). Letting Clerk's
  // middleware 404 them meant the upstream never got a chance to
  // authenticate — every chat/sessions call returned 404 from the
  // dashboard. Same for the SSE observability stream — its long-
  // lived response can't tolerate Clerk's redirect-on-401 behavior.
  "/api/ai-insights/(.*)",
  // All /api/orgs/* routes are pass-through proxies. The orgId in
  // the path is just a routing key for FastAPI; the actual auth
  // happens at the FastAPI edge via the Bearer header (or the
  // forwarded cookies). Letting Clerk's ``auth.protect()`` 404
  // them meant every dashboard call failed with a bare 404 instead
  // of letting the upstream return a proper 401 envelope. July 2026
  // site-wide fix.
  "/api/orgs/(.*)",
  // Same logic for /api/agents/* — the dedicated multipart upload
  // route and the test-runs / sim-runs endpoints are all auth-
  // gated by FastAPI, not by Clerk middleware. Without this entry
  // Clerk's protect() returned ``x-clerk-auth-reason: protect-
  // rewrite`` 404s on every call.
  "/api/agents/(.*)",
  "/api/orgs/(.*)/observability/stream",
  "/__clerk(.*)",
  "/sign-in(.*)",
  "/sign-up(.*)",
]);

/**
 * Middleware (Next 16 renamed `middleware.ts` → `proxy.ts`). Clerk's
 * `clerkMiddleware()` returns the actual Next.js middleware function;
 * protected-first auth gating lives inside.
 */
export default clerkMiddleware(async (auth, request: NextRequest) => {
  const url = new URL(request.url);
  const path = url.pathname;

  // Lab compile-signal spends OPENROUTER_API_KEY in the Next handler —
  // require a Clerk session at the edge (handler also checks auth()).
  if (path.startsWith("/api/lab/")) {
    const { userId } = await auth();
    if (!userId) {
      return NextResponse.json({ detail: "Unauthorized" }, { status: 401 });
    }
  }

  // Auth gate — only known portal prefixes require a session.
  //
  // Explicit redirect (not bare auth.protect()): with Next 16 + empty
  // NEXT_PUBLIC_CLERK_SIGN_IN_URL at edge, protect() can rewrite to
  // [...notFound] (404) instead of /sign-in. Manual redirect is reliable.
  //
  // Returns the sign-in bounce, or null when the request may proceed.
  // This bounce must always be a *redirect*: the browser has to end up
  // on Clerk's sign-in page with `redirect_url` visible in the address
  // bar, and Clerk reads it from there to send the user back. Rewriting
  // would render sign-in under the protected URL and lose the return
  // trip entirely.
  const enforcePortalAuth = async () => {
    // Wave 4: /api/proxy requires a Clerk session (removed from
    // isPublicRoute). Session cookies + auth().getToken() still
    // work inside the route handler once this gate passes.
    const isProxyPath =
      path === "/api/proxy" || path.startsWith("/api/proxy/");
    const isKnownProtected =
      isProxyPath ||
      KNOWN_PORTAL_PREFIXES.some(
        (p) => path === p || path.startsWith(p + "/"),
      );
    if (!isKnownProtected || isPublicRoute(request)) return null;
    const { userId } = await auth();
    if (userId) return null;
    const dest = new URL("/sign-in", url.origin);
    dest.searchParams.set("redirect_url", `${path}${url.search}`);
    return NextResponse.redirect(dest);
  };

  const hubTarget = resolveHubTarget(path, url.search);
  if (hubTarget) {
    if (hubTarget.mode === "rewrite") {
      // A rewrite is served in this same pass, so it never re-enters
      // this middleware — the auth gate the redirect branch got for
      // free from the follow-up request has to run explicitly here, or
      // the rewritten route would be reachable without a session.
      const bounce = await enforcePortalAuth();
      if (bounce) return bounce;
      return NextResponse.rewrite(new URL(hubTarget.destination, url.origin));
    }
    return NextResponse.redirect(
      new URL(hubTarget.destination, url.origin),
      307,
    );
  }

  const bounce = await enforcePortalAuth();
  if (bounce) return bounce;

  return NextResponse.next();
},
{
  signInUrl: "/sign-in",
  signUpUrl: "/sign-up",
});

export const config = {
  matcher: [
    // Skip static assets AND the lean /api/health edge probe so uptime
    // monitors never pay Clerk middleware cold-start cost.
    "/((?!_next|api/health(?:$|\\?)|[^?]*\\.(?:html?|css|js(?!on)|jpe?g|webp|png|gif|svg|avif|mp4|webm|wasm|map|ttf|woff2?|ico|csv|docx?|xlsx?|zip|webmanifest|txt|xml)).*)",
    // Always run on API + TRPC routes except /api/health (covered above).
    "/api/((?!health$).*)",
    "/trpc/(.*)",
    // Always run on Clerk's own auto-proxy path (after the API matcher).
    "/__clerk/:path*",
  ],
};
