import { clerkMiddleware, createRouteMatcher } from "@clerk/nextjs/server";
import createIntlMiddleware from "next-intl/middleware";
import { NextResponse } from "next/server";
import { routing } from "@/i18n/routing";

// Protected-first: block everything, allow the routes that must stay
// reachable without a session (marketing pages, auth flows, the
// catch-all proxy to FastAPI, and Clerk's own internal callbacks).
//
// /api/health is a public, unauthenticated health probe so uptime
// monitors and the auth-card status badge can call it without
// needing a Clerk session. /api/auth/me and /api/auth/refresh are
// the proxy's own Clerk-aware endpoints — they accept ANY token
// (Clerk JWT, Eden cookie, anonymous) and decide themselves, so
// they must NOT be gated by Clerk middleware. /api/auth/login + /signup
// are the legacy Eden cookie flow, also unauthenticated.
const isPublicRoute = createRouteMatcher([
  "/",
  "/login(.*)",
  "/signup(.*)",
  "/forgot-password(.*)",
  "/reset-password(.*)",
  "/invite(.*)",
  "/docs(.*)",
  // Marketing / legal pages — must be public so anonymous browsers
  // and search-engine crawlers can fetch them. Without this, the
  // Clerk middleware 404s them (which is a real bug the user
  // reported: "loads of 404, not found"). July 2026 fix.
  "/privacy(.*)",
  "/security(.*)",
  "/terms(.*)",
  "/dpa(.*)",
  // SEO files — generated by Next.js (robots.ts, sitemap.ts) and
  // served as static. Must be public or crawlers get 404.
  "/robots.txt",
  "/sitemap.xml",
  "/api/proxy/(.*)",  // explicit / after proxy so the matcher sees
                        // segments, not just a trailing string
  "/api/health",
  "/api/auth/me",
  "/api/auth/refresh",
  "/api/auth/me/debug",
  "/api/auth/login",
  "/api/auth/signup",
  "/api/auth/logout",
  // ai-insights routes are pass-through proxies that forward the
  // request cookie + Clerk Bearer to FastAPI, which does its own
  // auth (returns 401 on bad/missing token). Letting Clerk's
  // middleware 404 them meant the upstream never got a chance to
  // authenticate — every chat/sessions call returned 404 from the
  // dashboard. Same for the SSE observability stream — its long-
  // lived response can't tolerate Clerk's redirect-on-401 behavior.
  "/api/ai-insights/(.*)",
  // All /api/orgs/* routes are pass-through proxies. The orgId in
  // the path is just a routing key for FastAPI; the actual auth
  // happens at the FastAPI edge via the Bearer header (or the
  // forwarded cookies). Letting Clerk's ``auth.protect()`` 404
  // them meant every dashboard call failed with a bare 404 instead
  // of letting the upstream return a proper 401 envelope. July 2026
  // site-wide fix.
  "/api/orgs/(.*)",
  // Same logic for /api/agents/* — the dedicated multipart upload
  // route and the test-runs / sim-runs endpoints are all auth-
  // gated by FastAPI, not by Clerk middleware. Without this entry
  // Clerk's protect() returned ``x-clerk-auth-reason: protect-
  // rewrite`` 404s on every call.
  "/api/agents/(.*)",
  "/api/orgs/(.*)/observability/stream",
  "/__clerk(.*)",
  "/sign-in(.*)",
  "/sign-up(.*)",
  // i18n: locale-prefixed root is `/de` + `/de/...` for non-default
  // locales. The default locale (`en`) stays unprefixed at `/`. See
  // `src/i18n/routing.ts` for the prefix mode.
  "/de",
  "/de/(.*)",
]);

// next-intl middleware: reads/writes the `NEXT_LOCALE` cookie,
// optionally redirects `/` → `/de` when the user's accept-language
// (or stored cookie) asks for German without the prefix.
const intlMiddleware = createIntlMiddleware(routing);

/**
 * Combined middleware chain.
 *
 * Why both Clerk AND next-intl live in one file: Next 16 renamed
 * `middleware.ts` → `proxy.ts` and there can only be one. Clerk's
 * `clerkMiddleware()` returns the actual Next.js middleware
 * function, so we wrap it and call `intlMiddleware` first inside.
 *
 * Order: next-intl runs first (it may redirect to add a `/de`
 * prefix). If it redirects, we return that response directly and
 * Clerk never sees the request. Otherwise we run Clerk's auth gate
 * and forward any cookies intl set on the way out.
 *
 * Clerk's `auth.protect()` only fires for non-public routes, so the
 * locale switch on the public marketing page never hits Clerk's
 * auth state — which is what we want.
 */
export default clerkMiddleware(async (auth, request) => {
  const intlResponse = intlMiddleware(request);

  // next-intl wants a redirect (e.g. `/` → `/de` because the
  // accept-language header says so). Return it untouched — Clerk
  // doesn't need to run for a locale-prefix redirect.
  if (intlResponse.headers.get("location")) {
    return intlResponse;
  }

  if (!isPublicRoute(request)) {
    await auth.protect();
  }

  // Copy the locale cookie(s) from intl's response onto the response
  // we're about to return. Clerk's wrapper will merge this with its
  // own auth cookies when it emits the final response.
  const response = NextResponse.next({
    request: { headers: request.headers },
  });
  for (const cookie of intlResponse.cookies.getAll()) {
    response.cookies.set(cookie);
  }
  return response;
});

export const config = {
  matcher: [
    // Run on everything except Next internals + static files.
    "/((?!_next|[^?]*\\.(?:html?|css|js(?!on)|jpe?g|webp|png|gif|svg|ttf|woff2?|ico|csv|docx?|xlsx?|zip|webmanifest)).*)",
    // Always run on API + TRPC routes.
    "/(api|trpc)(.*)",
    // Always run on Clerk's own auto-proxy path (after the API matcher).
    "/__clerk/:path*",
  ],
};