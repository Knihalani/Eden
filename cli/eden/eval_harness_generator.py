def _infer_target_module(detection: FrameworkDetection, repo_root: Path) -> str:
    """Pick a sensible default ``<module>:<callable>`` for the target.

    ``detection.entry_points`` are repo-relative paths. We read the
    file's source and look for a top-level ``def run()`` /
    ``def main()`` to choose the callable name.
    """
    if detection.entry_points:
        first_rel = detection.entry_points[0]
        # ``first_rel`` is a repo-relative path; turn it into a Python
        # module name by dropping the .py extension and converting
        # path separators to dots (e.g. "src/agent.py" -> "src.agent").
        rel = first_rel.replace(str(repo_root) + "/", "")
        stem = Path(rel).stem
        module = stem.replace("/", ".").lstrip(".")
        abs_path = repo_root / rel
        try:
            text = abs_path.read_text(encoding="utf-8", errors="replace")[:20_000]
        except OSError:
            text = ""
        if re.search(r"^def\s+run\s*\(", text, re.MULTILINE):
            return f"{module}:run"
        if re.search(r"^def\s+main\s*\(", text, re.MULTILINE):
            return f"{module}:main"
    return "agent:run"


def _yaml_dump(data: Any) -> str:
    if yaml is None:  # pragma: no cover
        return json.dumps(data, indent=2)
    return yaml.safe_dump(data, sort_keys=False).rstrip()


def build_eval_harness(
    repo_root: str | Path,
    detection: FrameworkDetection,
    *,
    use_server_pipeline: bool = False,
    server_pipeline_endpoint: Optional[str] = None,
    extra_test_cases: Optional[List[EvalTestCase]] = None,
) -> EvalHarness:
    """Build a complete local eval harness for the target agent.

    Args:
        repo_root: Target repo root (used only to infer a default module).
        detection: Framework detection result.
        use_server_pipeline: When True, the harness may forward to the
            server pipeline. Defaults to False so the harness works on
            installations where ``enable_eval_pipeline=false``.
        server_pipeline_endpoint: Server pipeline endpoint (optional).
        extra_test_cases: Additional test cases to append.
    """
    root = Path(repo_root).expanduser().resolve()
    framework = detection.framework
    target = _infer_target_module(detection, root)
    cases = list(DEFAULT_TEST_CASES.get(framework, DEFAULT_TEST_CASES["custom"]))
    if extra_test_cases:
        cases.extend(extra_test_cases)

    criteria = dict(DEFAULT_CRITERIA)
    criteria_yaml = _yaml_dump(criteria)
    test_cases_yaml = _yaml_dump([tc.__dict__ for tc in cases])

    yaml_content = EVAL_YAML_TEMPLATE.format(
        framework=framework,
        target_module=target,
        use_server_pipeline=str(use_server_pipeline).lower(),
        server_pipeline_endpoint=f'"{server_pipeline_endpoint}"' if server_pipeline_endpoint else "null",
        criteria_yaml=criteria_yaml,
        test_cases_yaml=test_cases_yaml,
    )

    harness = EvalHarness(
        framework=framework,
        target_module=target,
        test_cases=cases,
        criteria=criteria,
        use_server_pipeline=use_server_pipeline,
        server_pipeline_endpoint=server_pipeline_endpoint,
        notes=[
            "Local harness: run `python eden_eval_harness.py` to execute.",
            "Pytest wrapper: `pytest tests/test_eden_eval.py`.",
            "Toggle `use_server_pipeline: true` in eden-eval.yaml to forward "
            "to the Eden server pipeline once that feature is enabled.",
        ],
    )

    harness.files.append(
        {
            "path": "eden-eval.yaml",
            "operation": "create",
            "description": "Declarative eval config",
            "content": yaml_content,
        }
    )
    harness.files.append(
        {
            "path": "eden_eval_harness.py",
            "operation": "create",
            "description": "Python eval harness runner",
            "content": PYTHON_HARNESS_TEMPLATE,
        }
    )
    harness.files.append(
        {
            "path": "tests/test_eden_eval.py",
            "operation": "create",
            "description": "Pytest wrapper around the harness",
            "content": PYTEST_TEST_TEMPLATE,
        }
    )

    return harness


def apply_harness(
    repo_root: str | Path,
    harness: EvalHarness,
    *,
    only: Optional[List[str]] = None,
) -> List[str]:
    """Write a harness bundle to disk. Returns paths actually written."""
    root = Path(repo_root).expanduser().resolve()
    written: List[str] = []
    for f in harness.files:
        if only and f["path"] not in only:
            continue
        target = root / f["path"]
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists() and f["operation"] != "create":
            continue
        target.write_text(f["content"], encoding="utf-8")
        written.append(f["path"])
    return written
