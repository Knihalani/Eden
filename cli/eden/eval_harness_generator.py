"""Local eval harness generator for `/integrate-eden`.

Generates a self-contained, runnable eval harness around a target
agent. Crucially, **the harness does not depend on the Eden server
pipeline** — it is meant to work even when
``enable_eval_pipeline=false`` on the server. A flag on the
``EdenEvalHarness`` lets the user opt-in to the server pipeline once
the feature is enabled.

Output of :func:`build_eval_harness`:

- ``eden-eval.yaml`` — declarative config (test cases, criteria, pass
  thresholds).
- ``eden_eval_harness.py`` — Python wrapper that runs the eval loop
  against the target agent module.
- ``tests/test_eden_eval.py`` — pytest wrapper that invokes the
  harness and asserts pass/fail.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

try:
    import yaml  # type: ignore
except ImportError:  # pragma: no cover
    yaml = None  # type: ignore

from eden.framework_detector import FrameworkDetection


@dataclass
class EvalTestCase:
    """A single test case for the eval harness."""

    name: str
    input: str
    expected_keywords: List[str] = field(default_factory=list)
    must_not_contain: List[str] = field(default_factory=list)
    timeout_seconds: int = 30


@dataclass
class EvalHarness:
    """The full local eval harness bundle."""

    framework: str
    target_module: str  # e.g. "agent:run"
    test_cases: List[EvalTestCase] = field(default_factory=list)
    criteria: Dict[str, Any] = field(default_factory=dict)
    use_server_pipeline: bool = False
    server_pipeline_endpoint: Optional[str] = None
    files: List[Dict[str, str]] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "framework": self.framework,
            "target_module": self.target_module,
            "use_server_pipeline": self.use_server_pipeline,
            "server_pipeline_endpoint": self.server_pipeline_endpoint,
            "criteria": self.criteria,
            "test_cases": [tc.__dict__ for tc in self.test_cases],
            "files": self.files,
            "notes": self.notes,
        }


