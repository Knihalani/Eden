"""Pull-request manager for `/eden-pr`.

Supports three backends:
  - **GitHub** (via PyGithub — optional dependency)
  - **GitLab** (via python-gitlab — optional dependency)
  - **Bitbucket** (via raw httpx)

The manager is intentionally transport-agnostic: callers pass a
``PRRequest`` and get back a ``PRResult``. Each backend is only
imported when first used, so the CLI keeps working even if the
optional deps aren't installed.

The manager also generates PR bodies from ``.eden/config.yaml``
templates and picks a branch name using the configured prefix.
"""

from __future__ import annotations

import os
import re
import subprocess  # nosec - we only run `git` for inspection, never arbitrary cmds
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------


@dataclass
class PRRequest:
    """Inputs for creating a pull request."""

    title: str
    body: str
    base_branch: str = "main"
    head_branch: str = ""
    draft: bool = False
    reviewers: List[str] = field(default_factory=list)
    labels: List[str] = field(default_factory=list)
    platform: str = "github"  # "github" | "gitlab" | "bitbucket"
    remote: str = "origin"
    # Authentication — at least one of (token, username+password) is
    # required depending on the platform.
    token: str = ""
    username: str = ""
    password: str = ""
    project_path: str = ""  # "<owner>/<repo>" for GitHub/Bitbucket, numeric for GitLab
    api_base: str = ""  # optional override (GitHub Enterprise, self-hosted GitLab)
    commit_message: str = ""


@dataclass
class PRResult:
    """Result of a PR creation attempt."""

    success: bool
    platform: str
    url: str = ""
    number: Optional[int] = None
    error: str = ""
    raw: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "success": self.success,
            "platform": self.platform,
            "url": self.url,
            "number": self.number,
            "error": self.error,
            "raw": self.raw,
        }


# ---------------------------------------------------------------------------
# Template rendering
# ---------------------------------------------------------------------------


# Built-in templates for PR body. We use a tiny ``str.format_map``-style
# replacement so callers can override via .eden/config.yaml without
# pulling in Jinja2.
DEFAULT_BODY_TEMPLATE = """\
## Summary
{summary}

## Eden Context
{eden_context}

## Changes
{changes}

## Test Results
{test_results}

## Checklist
- [ ] Code follows team conventions
- [ ] Tests pass
- [ ] No new security issues
- [ ] Documentation updated
"""


def render_pr_body(
    template: str,
    *,
    summary: str = "",
    eden_context: str = "Generated by `/eden-pr`.",
    changes: str = "- _No change list provided._",
    test_results: str = "Local eval harness not run.",
) -> str:
    """Render the PR body using a (tiny) template engine.

    The default template ships these placeholders:
      ``{summary}``, ``{eden_context}``, ``{changes}``, ``{test_results}``.
    A user-provided template may include any subset — missing
    placeholders are left as empty strings.
    """
    # We use a custom format_map that swallows KeyError for placeholders
    # the user didn't supply a value for. Standard ``str.format_map``
    # raises on missing keys, which is brittle.
    class _SafeDict(dict):
        def __missing__(self, key: str) -> str:  # type: ignore[override]
            return ""

    return template.format_map(
        _SafeDict(
            summary=summary,
            eden_context=eden_context,
            changes=changes,
            test_results=test_results,
        )
    )


def render_commit_message(
    template: str,
    *,
    summary: str = "update",
    files: Optional[List[str]] = None,
) -> str:
    """Render a commit message from a template.

    Supported placeholders: ``{summary}``, ``{files}``.
    """
    files_str = ", ".join(files or []) or "various files"
    return template.format_map({"summary": summary, "files": files_str})


# ---------------------------------------------------------------------------
# Branch helpers
# ---------------------------------------------------------------------------


_SLUG_NON_ALNUM = re.compile(r"[^a-z0-9]+")


def slugify(text: str, *, max_length: int = 50) -> str:
    """Make a git-branch-friendly slug out of free-form text."""
    s = text.lower().strip()
    s = _SLUG_NON_ALNUM.sub("-", s).strip("-")
    return s[:max_length] or "update"


def build_branch_name(
    prefix: str,
    summary: str,
    *,
    max_length: int = 60,
) -> str:
    """Combine a configured prefix and a slugified summary into a branch
    name. Strips stray slashes to avoid double-prefixes."""
    p = prefix.strip().strip("/")
    if p and not p.endswith("/"):
        p = p + "/"
    slug = slugify(summary, max_length=max_length - len(p) - 1)
    return f"{p}{slug}"


# ---------------------------------------------------------------------------
# Git inspection helpers (no writes, no remote pushes)
# ---------------------------------------------------------------------------


def _run_git(*args: str, cwd: Optional[Path] = None) -> str:
    """Run a read-only git command and return stdout."""
    try:
        proc = subprocess.run(  # nosec
            ["git", *args],
            capture_output=True,
            text=True,
            check=True,
            cwd=str(cwd) if cwd else None,
            timeout=15,
        )
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        raise RuntimeError(f"git {' '.join(args)} failed: {exc}") from exc
    return proc.stdout.strip()


def current_branch(cwd: Optional[Path] = None) -> str:
    return _run_git("rev-parse", "--abbrev-ref", "HEAD", cwd=cwd)


def has_uncommitted_changes(cwd: Optional[Path] = None) -> bool:
    out = _run_git("status", "--porcelain", cwd=cwd)
    return bool(out.strip())


def list_changed_files(cwd: Optional[Path] = None) -> List[str]:
    """Return the list of files changed against the configured base branch
    (or HEAD~1 if no base known). Used to populate the PR body."""
    try:
        out = _run_git("diff", "--name-only", "HEAD~1..HEAD", cwd=cwd)
    except RuntimeError:
        # No prior commit — fall back to status.
        out = _run_git("status", "--porcelain", cwd=cwd)
        out = "\n".join(line.split(maxsplit=1)[-1] for line in out.splitlines())
    return [f for f in out.splitlines() if f]


# ---------------------------------------------------------------------------
# Backend dispatcher
# ---------------------------------------------------------------------------


def create_pull_request(
    req: PRRequest,
    *,
    cwd: Optional[Path] = None,
) -> PRResult:
    """Create a pull request on the configured platform.

    The actual API call is dispatched to a per-platform function. Each
    function returns a ``PRResult``. We never push the branch from
    here — that's the caller's responsibility (so they can apply
    autonomy / branch-protection checks first).
    """
    platform = (req.platform or "github").lower()
    if platform == "github":
        return _create_github_pr(req, cwd=cwd)
    if platform == "gitlab":
        return _create_gitlab_pr(req, cwd=cwd)
    if platform == "bitbucket":
        return _create_bitbucket_pr(req, cwd=cwd)
    return PRResult(
        success=False,
        platform=platform,
        error=f"unknown platform: {platform!r}",
    )


# ---------------------------------------------------------------------------
# GitHub
# ---------------------------------------------------------------------------


def _create_github_pr(req: PRRequest, *, cwd: Optional[Path] = None) -> PRResult:
    try:
        from github import Github  # type: ignore
    except ImportError:
        return PRResult(
            success=False,
            platform="github",
            error="PyGithub is not installed. Install with `pip install pygithub`.",
        )
    if not req.token:
        return PRResult(
            success=False,
            platform="github",
            error="missing GitHub token (set EDEN_GITHUB_TOKEN or .eden/config.yaml pr.token).",
        )
    if not req.project_path or "/" not in req.project_path:
        return PRResult(
            success=False,
            platform="github",
            error="project_path must be '<owner>/<repo>'.",
        )

    g = Github(req.token, base_url=req.api_base or None)
    try:
        repo = g.get_repo(req.project_path)
        pr = repo.create_pull(
            title=req.title,
            body=req.body,
            base=req.base_branch,
            head=req.head_branch,
            draft=req.draft,
        )
        # Reviewers / labels (best-effort).
        if req.reviewers:
            try:
                pr.create_review_request(reviewers=req.reviewers)
            except Exception:  # noqa: BLE001
                pass
        if req.labels:
            try:
                pr.add_to_labels(*req.labels)
            except Exception:  # noqa: BLE001
                pass
        return PRResult(
            success=True,
            platform="github",
            url=pr.html_url,
            number=pr.number,
            raw={"html_url": pr.html_url, "number": pr.number},
        )
    except Exception as exc:  # noqa: BLE001
        return PRResult(
            success=False,
            platform="github",
            error=f"GitHub API error: {exc}",
        )


# ---------------------------------------------------------------------------
# GitLab
# ---------------------------------------------------------------------------


def _create_gitlab_pr(req: PRRequest, *, cwd: Optional[Path] = None) -> PRResult:
    try:
        import gitlab  # type: ignore
    except ImportError:
        return PRResult(
            success=False,
            platform="gitlab",
            error="python-gitlab is not installed. Install with `pip install python-gitlab`.",
        )
    if not req.token:
        return PRResult(
            success=False,
            platform="gitlab",
            error="missing GitLab token.",
        )
    if not req.project_path:
        return PRResult(
            success=False,
            platform="gitlab",
            error="project_path (numeric project id) is required for GitLab.",
        )

    try:
        gl = gitlab.Gitlab(url=req.api_base or None, private_token=req.token)
        project = gl.projects.get(req.project_path)
        mr = project.mergerequests.create(
            {
                "source_branch": req.head_branch,
                "target_branch": req.base_branch,
                "title": req.title,
                "description": req.body,
                "draft": req.draft,
            }
        )
        if req.labels:
            try:
                mr.labels = req.labels
                mr.save()
            except Exception:  # noqa: BLE001
                pass
        return PRResult(
            success=True,
            platform="gitlab",
            url=mr.web_url,
            number=mr.iid,
            raw={"iid": mr.iid, "web_url": mr.web_url},
        )
    except Exception as exc:  # noqa: BLE001
        return PRResult(
            success=False,
            platform="gitlab",
            error=f"GitLab API error: {exc}",
        )


# ---------------------------------------------------------------------------
# Bitbucket
# ---------------------------------------------------------------------------


def _create_bitbucket_pr(req: PRRequest, *, cwd: Optional[Path] = None) -> PRResult:
    """Bitbucket Cloud REST API v2 (works for workspaces on bitbucket.org)."""
    try:
        import httpx  # type: ignore
    except ImportError:
        return PRResult(
            success=False,
            platform="bitbucket",
            error="httpx is required for the Bitbucket backend.",
        )
    if not (req.username and (req.token or req.password)):
        return PRResult(
            success=False,
            platform="bitbucket",
            error="Bitbucket requires username + app password (or token).",
        )
    if not req.project_path or "/" not in req.project_path:
        return PRResult(
            success=False,
            platform="bitbucket",
            error="project_path must be '<workspace>/<repo_slug>'.",
        )

    base = req.api_base.rstrip("/") if req.api_base else "https://api.bitbucket.org"
    url = f"{base}/2.0/repositories/{req.project_path}/pullrequests"
    payload = {
        "title": req.title,
        "description": req.body,
        "source": {"branch": {"name": req.head_branch}},
        "destination": {"branch": {"name": req.base_branch}},
        "draft": req.draft,
    }
    try:
        with httpx.Client(timeout=15.0) as client:
            resp = client.post(
                url,
                json=payload,
                auth=(req.username, req.token or req.password),
            )
        if resp.status_code >= 400:
            return PRResult(
                success=False,
                platform="bitbucket",
                error=f"Bitbucket API {resp.status_code}: {resp.text[:300]}",
            )
        data = resp.json()
        links = data.get("links", {})
        return PRResult(
            success=True,
            platform="bitbucket",
            url=links.get("html", {}).get("href", ""),
            number=data.get("id"),
            raw=data,
        )
    except Exception as exc:  # noqa: BLE001
        return PRResult(
            success=False,
            platform="bitbucket",
            error=f"Bitbucket request error: {exc}",
        )
