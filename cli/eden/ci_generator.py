"""CI config generator for `/integrate-eden`.

Generates:
  - ``.github/workflows/eden-eval.yml`` (GitHub Actions)
  - ``.gitlab-ci.yml`` (GitLab CI)
  - ``.eden/ci_config.yaml`` (shared snippet for other providers)

The generated CI runs the *local* eval harness (so it works without
``enable_eval_pipeline=true`` on the server). It can be flipped to
forward to the server pipeline by setting ``use_server_pipeline: true``
in ``eden-eval.yaml``.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional


@dataclass
class CIPlan:
    """Generated CI files."""

    files: List[Dict[str, str]] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "files": self.files,
            "notes": self.notes,
        }


GITHUB_ACTIONS_TEMPLATE = """\
# Generated by `/integrate-eden`. Runs the local Eden eval harness on
# every push and pull request. Toggle `use_server_pipeline: true` in
# eden-eval.yaml to forward to the Eden server pipeline.
name: eden-eval

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

jobs:
  eval:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: "3.11"

      - name: Install dependencies
        run: |
          python -m pip install --upgrade pip
          if [ -f requirements.txt ]; then pip install -r requirements.txt; fi
          pip install pyyaml

      - name: Run Eden eval harness
        env:
          EDEN_API_KEY: ${{{{ secrets.EDEN_API_KEY }}}}
          EDEN_DEFAULT_ORG: ${{{{ secrets.EDEN_DEFAULT_ORG }}}}
          EDEN_BASE_URL: ${{{{ secrets.EDEN_BASE_URL }}}}
        run: |
          if [ -f eden_eval_harness.py ]; then
            python eden_eval_harness.py
          else
            echo "eden_eval_harness.py not found — skipping"
            exit 0
          fi

      - name: Run pytest wrapper
        run: |
          if [ -f tests/test_eden_eval.py ]; then
            python -m pip install pytest
            python -m pytest tests/test_eden_eval.py -v
          fi
"""


GITLAB_CI_TEMPLATE = """\
# Generated by `/integrate-eden`. Runs the local Eden eval harness on
# every push and merge request. Toggle `use_server_pipeline: true` in
# eden-eval.yaml to forward to the Eden server pipeline.
stages:
  - test

eden-eval:
  stage: test
  image: python:3.11
  variables:
    EDEN_API_KEY: ${EDEN_API_KEY}
    EDEN_DEFAULT_ORG: ${EDEN_DEFAULT_ORG}
    EDEN_BASE_URL: ${EDEN_BASE_URL:-http://localhost:8000}
  before_script:
    - python -m pip install --upgrade pip
    - if [ -f requirements.txt ]; then pip install -r requirements.txt; fi
    - pip install pyyaml pytest
  script:
    - if [ -f eden_eval_harness.py ]; then python eden_eval_harness.py; fi
    - if [ -f tests/test_eden_eval.py ]; then python -m pytest tests/test_eden_eval.py -v; fi
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
    - if: $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH
"""


SHARED_CI_CONFIG = """\
# Generated by `/integrate-eden`. Shared CI configuration snippet.
# Copy the relevant `job:` block into your own provider's config.
# Provider-specific files (GitHub Actions, GitLab CI) live alongside this one.

eden_eval_job:
  image: python:3.11
  steps:
    - checkout
    - install: pip install -r requirements.txt pyyaml pytest
    - run: python eden_eval_harness.py
    - run: pytest tests/test_eden_eval.py -v
  env:
    EDEN_API_KEY: ${EDEN_API_KEY}
    EDEN_DEFAULT_ORG: ${EDEN_DEFAULT_ORG}
    EDEN_BASE_URL: ${EDEN_BASE_URL:-http://localhost:8000}
"""


def build_ci_plan(
    repo_root: str | Path,
    *,
    providers: Optional[List[str]] = None,
) -> CIPlan:
    """Build a CI plan for the requested providers.

    Args:
        repo_root: Target repo root (used to avoid clobbering existing
            CI configs).
        providers: List of providers to emit. Defaults to
            ``["github", "gitlab"]``. Pass an empty list to skip CI
            generation entirely.
    """
    root = Path(repo_root).expanduser().resolve()
    plan = CIPlan()

    if providers is None:
        providers = ["github", "gitlab"]

    if "github" in providers:
        target = root / ".github" / "workflows" / "eden-eval.yml"
        plan.files.append(
            {
                "path": ".github/workflows/eden-eval.yml",
                "operation": "create",
                "description": "GitHub Actions workflow for the Eden eval harness",
                "content": GITHUB_ACTIONS_TEMPLATE,
            }
        )
        if target.exists():
            plan.notes.append(
                ".github/workflows/eden-eval.yml already exists — skipped (rerun with --force)."
            )
            plan.files.pop()

    if "gitlab" in providers:
        target = root / ".gitlab-ci.yml"
        if target.exists():
            plan.notes.append(
                ".gitlab-ci.yml already exists — skipped. Append the "
                "snippet from `.eden/ci_config.yaml` manually to avoid "
                "clobbering your existing config."
            )
        else:
            plan.files.append(
                {
                    "path": ".gitlab-ci.yml",
                    "operation": "create",
                    "description": "GitLab CI config for the Eden eval harness",
                    "content": GITLAB_CI_TEMPLATE,
                }
            )

    # Always emit the shared snippet as a reference.
    plan.files.append(
        {
            "path": ".eden/ci_config.yaml",
            "operation": "create",
            "description": "Shared CI snippet reference",
            "content": SHARED_CI_CONFIG,
        }
    )
    return plan


def apply_ci_plan(
    repo_root: str | Path,
    plan: CIPlan,
    *,
    only: Optional[List[str]] = None,
) -> List[str]:
    """Write CI plan to disk. Returns paths actually written."""
    root = Path(repo_root).expanduser().resolve()
    written: List[str] = []
    for f in plan.files:
        if only and f["path"] not in only:
            continue
        target = root / f["path"]
        if target.exists() and f["operation"] == "create":
            # Skip if file already exists (safety: never clobber CI configs).
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(f["content"], encoding="utf-8")
        written.append(f["path"])
    return written
