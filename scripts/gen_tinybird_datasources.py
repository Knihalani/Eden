#!/usr/bin/env python
"""Generate ``tinybird/datasources/*.datasource`` from the ClickHouse DDL.

The committed datasources were auto-generated from NDJSON samples
(``DESCRIPTION > Generated from /tmp/sample_*.ndjson``), which is why every
type came out as the widest thing JSON inference could justify. Against the
Python DDL in ``data_platform/clickhouse_sink.py`` that produced roughly forty
mismatches across five tables:

* all 17 ``LowCardinality(String)`` columns became plain ``String`` — the
  single largest compression regression on the Tinybird side
* all 6 ``DateTime64(3)`` became ``DateTime``, **truncating to whole seconds**,
  which destroys span ordering within a trace
* all 9 ``UUID`` became ``String`` (16 bytes to ~36), and ``toUUID()`` in
  ``query_agent_performance`` is valid against one substrate and a type error
  against the other
* all 7 ``Float64`` became ``Float32``, including three currency columns
* every unsigned integer became signed (``UInt32``→``Int32``,
  ``UInt8``→``Int16``)
* the ``date DEFAULT toDate(timestamp)`` column was missing from all four
  tables that define it

Two schemas for one logical table is not a drift problem to be re-fixed each
time it recurs; it is a missing generator. The DDL is the source of truth and
this script derives the datasources from it, so the only way to change a
Tinybird schema is to change the DDL and re-run.

Usage:
    python scripts/gen_tinybird_datasources.py           # write the files
    python scripts/gen_tinybird_datasources.py --check   # fail if stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SINK = ROOT / "src/eden/data_platform/clickhouse_sink.py"
OUT_DIR = ROOT / "tinybird/datasources"

#: Tables that live in Tinybird. The rollups are ClickHouse-side materialized
#: views; they have no Tinybird endpoint and are excluded deliberately rather
#: than by omission.
TINYBIRD_TABLES = (
    "agent_performance",
    "pipeline_stages",
    "usage_trends",
    "benchmark_results",
    "telemetry_events_ch",
)

_HEADER = (
    "DESCRIPTION >\n"
    "    Generated by scripts/gen_tinybird_datasources.py from the\n"
    "    CREATE TABLE in src/eden/data_platform/clickhouse_sink.py.\n"
    "    Do not hand-edit: run the script instead, or the two schemas drift\n"
    "    (they previously disagreed on ~40 column types).\n"
)


class Table:
    def __init__(self, name: str) -> None:
        self.name = name
        self.columns: list[tuple[str, str, str | None]] = []  # (name, type, default)
        self.indexes: list[str] = []
        self.engine = "MergeTree"
        self.partition_by = ""
        self.sorting_key = ""
        self.ttl = ""


def _strip_codec(decl: str) -> str:
    """Remove a trailing ``CODEC(...)``, counting nested parentheses."""
    i = decl.upper().find("CODEC(")
    if i < 0:
        return decl.strip()
    open_paren = i + len("CODEC(") - 1  # index of the '(' itself
    depth = 0
    for j in range(open_paren, len(decl)):
        if decl[j] == "(":
            depth += 1
        elif decl[j] == ")":
            depth -= 1
            if depth == 0:
                return (decl[:i] + decl[j + 1 :]).strip()
    # Unbalanced — drop everything from CODEC onward rather than emit garbage.
    return decl[:i].strip()


def _translate_ttl(expr: str) -> str:
    """Rewrite ``X + INTERVAL 90 DAY`` into Tinybird's function form.

    The committed files used ``toIntervalDay(2555)`` for ``INTERVAL 7 YEAR``,
    which ignores leap days and drifts ~2 days from the DDL. Use the matching
    unit instead so the two are exactly equivalent.
    """
    m = re.match(r"(.+?)\s*\+\s*INTERVAL\s+(\d+)\s+(\w+)\s*$", expr.strip())
    if not m:
        return expr.strip()
    base, n, unit = m.group(1).strip(), m.group(2), m.group(3).upper()
    fn = {
        "DAY": "toIntervalDay",
        "MONTH": "toIntervalMonth",
        "YEAR": "toIntervalYear",
        "HOUR": "toIntervalHour",
    }.get(unit)
    if fn is None:
        return expr.strip()
    return f"{base} + {fn}({n})"


def parse_ddl(source: str) -> dict[str, Table]:
    """Pull each ``CREATE TABLE`` out of the sink module."""
    tables: dict[str, Table] = {}
    pattern = re.compile(
        r"CREATE TABLE IF NOT EXISTS \{self\.config\.database\}\.(\w+)\s*\((.*?)\)\s*\n"
        r"\s*ENGINE\s*=\s*(\w+)\(\)(.*?)(?:\"\"\")",
        re.S,
    )
    for m in pattern.finditer(source):
        name, body, engine, tail = m.groups()
        t = Table(name)
        t.engine = engine
        for raw in body.split("\n"):
            line = raw.strip().rstrip(",").strip()
            if not line:
                continue
            if line.upper().startswith("INDEX "):
                t.indexes.append(line)
                continue
            # ``name Type [CODEC(...)] [DEFAULT expr]``
            cm = re.match(r"^(\w+)\s+(.+)$", line)
            if not cm:
                continue
            col, rest = cm.group(1), cm.group(2).strip()
            default = None
            dm = re.search(r"\bDEFAULT\s+(.+)$", rest)
            if dm:
                default = dm.group(1).strip()
                rest = rest[: dm.start()].strip()
            # Codecs are a ClickHouse-side storage concern; Tinybird manages
            # compression for its own datasources, so only the *type* has to
            # agree. Strip the clause.
            #
            # ``CODEC\([^)]*\)`` does not work here: ``CODEC(Delta, ZSTD(3))``
            # nests parentheses, so the character class stops at the first
            # ``)`` and the substitution silently does not apply — the first
            # run of this script emitted the codecs verbatim.
            rest = _strip_codec(rest)
            t.columns.append((col, rest, default))
        for key, attr in (
            (r"PARTITION BY\s+([^\n]+)", "partition_by"),
            (r"ORDER BY\s+([^\n]+)", "sorting_key"),
            (r"TTL\s+([^\n]+)", "ttl"),
        ):
            km = re.search(key, tail)
            if km:
                value = km.group(1).strip()
                # ``ORDER BY (a, b)`` -> ``a, b``: Tinybird's
                # ENGINE_SORTING_KEY is a bare comma-separated list, which is
                # also what the previously committed files used.
                if attr == "sorting_key" and value.startswith("(") and value.endswith(")"):
                    value = value[1:-1].strip()
                setattr(t, attr, value)
        tables[name] = t
    return tables


def render(t: Table, *, forward_query: str | None = None) -> str:
    lines = [_HEADER, "\nSCHEMA >\n"]
    body: list[str] = []
    for col, ctype, default in t.columns:
        # Tinybird Forward requires a jsonpath on every SCHEMA column
        # (``Column X has no jsonpath`` otherwise). Keep DEFAULT so a
        # missing JSON field still materializes the derived value.
        if default is not None:
            body.append(f"    {col} {ctype} `json:$.{col}` DEFAULT {default}")
        else:
            body.append(f"    {col} {ctype} `json:$.{col}`")
    lines.append(",\n".join(body) + "\n")
    if t.indexes:
        lines.append("\nINDEXES >\n")
        lines.append("\n".join(f"    {ix}" for ix in t.indexes) + "\n")
    lines.append(f'\nENGINE "{t.engine}"\n')
    if t.partition_by:
        lines.append(f'ENGINE_PARTITION_KEY "{t.partition_by}"\n')
    if t.sorting_key:
        lines.append(f'ENGINE_SORTING_KEY "{t.sorting_key}"\n')
    if t.ttl:
        lines.append(f'ENGINE_TTL "{_translate_ttl(t.ttl)}"\n')
    if forward_query:
        # Preserve an existing FORWARD_QUERY across regenerations so a
        # mid-migration deploy does not lose the cast plan Tinybird needs.
        lines.append(f"\nFORWARD_QUERY >\n    {forward_query.strip()}\n")
    return "".join(lines)


_FORWARD_RE = re.compile(
    r"FORWARD_QUERY\s*>\s*\n(?P<body>.*?)(?=\n[A-Z_]+\s|>\s*$|\Z)",
    re.S,
)


def _existing_forward_query(path: Path) -> str | None:
    if not path.exists():
        return None
    m = _FORWARD_RE.search(path.read_text())
    if not m:
        return None
    return " ".join(m.group("body").split())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if any file on disk differs from what the DDL implies",
    )
    args = ap.parse_args()

    tables = parse_ddl(SINK.read_text())
    missing = [n for n in TINYBIRD_TABLES if n not in tables]
    if missing:
        print(f"FAIL: no CREATE TABLE found for {missing}", file=sys.stderr)
        return 2

    stale: list[str] = []
    for name in TINYBIRD_TABLES:
        path = OUT_DIR / f"{name}.datasource"
        want = render(tables[name], forward_query=_existing_forward_query(path))
        have = path.read_text() if path.exists() else ""
        if have == want:
            continue
        if args.check:
            stale.append(name)
        else:
            path.write_text(want)
            print(f"wrote {path.relative_to(ROOT)}")

    if args.check and stale:
        print(
            "FAIL: these .datasource files no longer match the ClickHouse DDL:\n"
            + "\n".join(f"  - {n}" for n in stale)
            + "\n\nRun: python scripts/gen_tinybird_datasources.py",
            file=sys.stderr,
        )
        return 1
    if args.check:
        print(f"OK: all {len(TINYBIRD_TABLES)} datasources match the DDL")
    return 0


if __name__ == "__main__":
    sys.exit(main())
