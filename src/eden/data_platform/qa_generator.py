"""Synthetic Q/A generation (Phase J — RagaAI parity).

Generates (question, answer, context) triples from raw text
sources (PDF-extracted, plain text, markdown, CSV). Three
output styles:

  * **extractive** — the answer is verbatim a sentence from
    the source. The question is templated from the sentence
    topic. Highest faithfulness; lowest diversity.
  * **abstractive** — the answer is a paraphrased summary
    of one or more sentences. Generated by an LLM (slot=fast).
    Higher diversity; lower faithfulness.
  * **multi-hop** — the answer is composed of two or more
    pieces of evidence that must be combined. The question
    is templated to require both. Tests a model's ability to
    reason across sources.

The generator is the second half of Phase J — Phase K ships
the FakerVault (which mints deterministic fake names /
emails / SSNs); this module consumes it so that real PII
in the source text is swapped for fakes before the Q/A
triples are persisted. The output is a batch of
:class:`SyntheticQA` records that can be:

  1. Streamed to a dataset (Cat 3 + Cat 12) for fine-tuning.
  2. Pushed to the labeling queue (Phase D) for human review.
  3. Shipped as a RagaAI-style "synthetic test set" alongside
     the real dataset.

Pipeline
────────
  raw text (PDF / markdown / text / CSV)
        │
        ▼  parse + chunk (overlapping windows)
        │
        ▼  PII swap (FakerVault) on every chunk
        │
        ▼  for each chunk: 1+ Q/A triples (extractive default)
        │
        ▼  optional: abstractive rewrite via LLM (slot=fast)
        │
        ▼  optional: multi-hop composition across chunks
        │
        ▼  SyntheticQA batch (id, question, answer, context,
                              source_chunk_id, type, locale, tags)
"""

from __future__ import annotations

import csv
import hashlib
import io
import logging
import re
from dataclasses import dataclass, field
from typing import Any, Iterable, Optional

from eden.data_platform.faker_vault import FakerVault, get_default_vault


logger = logging.getLogger(__name__)


# ── Defaults ──────────────────────────────────────────────────────

DEFAULT_CHUNK_SIZE = 800       # characters
DEFAULT_CHUNK_OVERLAP = 100    # characters of overlap between adjacent chunks
DEFAULT_QA_PER_CHUNK = 3       # extractive Q/A triples per chunk (extractive)
MAX_CONTEXT_CHARS = 2000       # hard cap on context length per triple


# ── Q/A types ─────────────────────────────────────────────────────

QA_TYPE_EXTRACTIVE = "extractive"
QA_TYPE_ABSTRACTIVE = "abstractive"
QA_TYPE_MULTI_HOP = "multi_hop"

ALL_QA_TYPES = frozenset({
    QA_TYPE_EXTRACTIVE,
    QA_TYPE_ABSTRACTIVE,
    QA_TYPE_MULTI_HOP,
})


# ── Dataclass ─────────────────────────────────────────────────────


@dataclass
class SyntheticQA:
    """One synthetic (question, answer, context) triple."""

    id: str
    question: str
    answer: str
    context: str
    source_chunk_id: str
    qa_type: str
    # Locale of the fakes used (en / es / ar / ja / etc).
    locale: str = "en"
    # Free-form tags for filtering / grouping.
    tags: list[str] = field(default_factory=list)
    # Difficulty rating 1-5. Extractive = 1 (easy), multi-hop
    # = 4-5 (hard), abstractive = 2-3.
    difficulty: int = 1
    # Provenance — which chunks contributed.
    source_chunks: list[str] = field(default_factory=list)
    # Optional metadata (e.g. model used for abstractive).
    metadata: dict[str, Any] = field(default_factory=dict)
    created_at: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "question": self.question,
            "answer": self.answer,
            "context": self.context,
            "source_chunk_id": self.source_chunk_id,
            "qa_type": self.qa_type,
            "locale": self.locale,
            "tags": list(self.tags),
            "difficulty": self.difficulty,
            "source_chunks": list(self.source_chunks),
            "metadata": dict(self.metadata),
            "created_at": self.created_at,
        }


# ── Text chunking ─────────────────────────────────────────────────


@dataclass
class TextChunk:
    """A window of source text. The id is content-addressed
    so the same chunk always gets the same id across runs.
    """

    id: str
    text: str
    start: int
    end: int
    source_format: str  # "text" | "markdown" | "csv" | "pdf"


def chunk_text(
    text: str,
    *,
    chunk_size: int = DEFAULT_CHUNK_SIZE,
    chunk_overlap: int = DEFAULT_CHUNK_OVERLAP,
    source_format: str = "text",
) -> list[TextChunk]:
    """Split ``text`` into overlapping windows.

    Sentence-aware when possible: the chunker prefers to
    break on sentence boundaries (``.`` / ``!`` / ``?``) so
    no answer is split across chunks. For markdown / CSV
    we also honour ``\\n\\n`` paragraph breaks.
    """
    if not text or not text.strip():
        return []
    if chunk_size <= 0:
        raise ValueError("chunk_size must be positive")
    if chunk_overlap < 0 or chunk_overlap >= chunk_size:
        raise ValueError("chunk_overlap must be in [0, chunk_size)")

    text = text.strip()
    chunks: list[TextChunk] = []
    pos = 0
    n = len(text)
    while pos < n:
        end = min(pos + chunk_size, n)
        # Try to break on the last sentence boundary in the
        # window.
        if end < n:
            window = text[pos:end]
            # Look for the last sentence terminator.
            best_break = -1
            for sep in ["\n\n", ". ", "! ", "? ", ".\n", "!\n", "?\n"]:
                idx = window.rfind(sep)
                if idx > best_break:
                    # Leave the separator in the chunk so the
                    # reader sees the full sentence.
                    best_break = idx + len(sep)
            if best_break > chunk_size // 2:
                end = pos + best_break
        chunk_text_str = text[pos:end].strip()
        if chunk_text_str:
            chunk_id = _chunk_id(chunk_text_str, source_format)
            chunks.append(TextChunk(
                id=chunk_id,
                text=chunk_text_str,
                start=pos,
                end=end,
                source_format=source_format,
            ))
        # Move forward by (chunk_size - overlap).
        if end >= n:
            break
        pos = max(end - chunk_overlap, pos + 1)
    return chunks


def _chunk_id(text: str, source_format: str) -> str:
    """Content-addressed chunk id."""
    h = hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
    return f"chunk-{source_format}-{h}"


# ── Q/A templates (extractive) ──────────────────────────────────


# Question templates — these turn a sentence into a Q. We pick
# the template based on the first verb / noun in the sentence.
# These are deliberately bland; the user is expected to
# customise via the ``extractive_templates`` kwarg.
EXTRACTIVE_TEMPLATES: tuple[str, ...] = (
    "What does the source say about {topic}?",
    "According to the text, what is {topic}?",
    "Describe {topic} as mentioned in the passage.",
    "What is the passage's position on {topic}?",
    "Explain the role of {topic} in the context.",
)


# Heuristics for picking the "topic" of a sentence: the first
# non-stopword noun phrase. We use a simple regex because we
# don't want to require NLTK / spacy for what's supposed to be
# a one-liner.
_STOPWORDS: frozenset[str] = frozenset({
    "the", "a", "an", "and", "or", "but", "if", "then", "this",
    "that", "these", "those", "is", "are", "was", "were", "be",
    "been", "being", "have", "has", "had", "do", "does", "did",
    "of", "in", "on", "at", "to", "for", "with", "by", "from",
    "as", "it", "its", "they", "them", "their", "he", "she",
    "his", "her", "we", "us", "our", "you", "your", "i", "me",
    "my", "what", "which", "who", "when", "where", "why", "how",
})


def _topic_of_sentence(sentence: str) -> str:
    """Pick a short topic phrase from a sentence.

    Strategy: first 3 consecutive non-stopword tokens. Falls
    back to the first 5 chars if no non-stopwords are found
    (shouldn't happen in practice).
    """
    words = re.findall(r"[A-Za-z][A-Za-z0-9_-]+", sentence)
    picked: list[str] = []
    for w in words:
        if w.lower() in _STOPWORDS:
            if picked:
                # End of the first noun phrase.
                break
            continue
        picked.append(w)
        if len(picked) >= 3:
            break
    if not picked:
        return sentence[:30].strip() or "the topic"
    return " ".join(picked)


def _split_sentences(text: str) -> list[str]:
    """Naive sentence splitter. Strips blank lines / whitespace.

    Handles ``.`` / ``!`` / ``?`` followed by whitespace as
    a sentence terminator. Abbreviations like "e.g." are not
    handled (we accept the false positive for the sake of
    zero dependencies).
    """
    text = text.strip()
    if not text:
        return []
    # Replace newlines that aren't paragraph breaks with spaces.
    text = re.sub(r"(?<!\n)\n(?!\n)", " ", text)
    # Split on sentence terminators + whitespace.
    parts = re.split(r"(?<=[.!?])\s+", text)
    return [p.strip() for p in parts if p.strip()]


# ── PII redaction pass ────────────────────────────────────────────


# Patterns we replace via FakerVault. These are *intentionally*
# simple — the production PII masker (Phase 7.3a + Phase K) is
# the source of truth. The point of the swap pass is to make
# sure the synthetic data doesn't leak obvious PII even if
# the source isn't fully masked.
_EMAIL_RE = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
_PHONE_RE = re.compile(r"\b(?:\+?1[-.\s]?)?\(?\d{3}\)?[-.\s]?\d{3}[-.\s]?\d{4}\b")
_SSN_RE = re.compile(r"\b\d{3}-\d{2}-\d{4}\b")


def _pii_swap_chunk(
    chunk: TextChunk,
    *,
    vault: FakerVault,
    locale: str = "en",
) -> TextChunk:
    """Replace obvious PII in a chunk with FakerVault fakes.

    Returns a new chunk; the input is untouched. The id is
    preserved (we want the chunk id to be content-addressed
    on the ORIGINAL text, so reruns are stable).
    """
    text = chunk.text
    # Email — preserve the local-part structure for the
    # faker (so the same input → same fake).
    def _email_sub(m: re.Match) -> str:
        return vault.fake_email(m.group(0))
    # Phone — use the digits as the vault key.
    def _phone_sub(m: re.Match) -> str:
        return vault.fake_phone(m.group(0))
    # SSN.
    def _ssn_sub(m: re.Match) -> str:
        return vault.fake_ssn(m.group(0))
    text = _EMAIL_RE.sub(_email_sub, text)
    text = _PHONE_RE.sub(_phone_sub, text)
    text = _SSN_RE.sub(_ssn_sub, text)
    return TextChunk(
        id=chunk.id,
        text=text,
        start=chunk.start,
        end=chunk.end,
        source_format=chunk.source_format,
    )


# ── Q/A generation ──────────────────────────────────────────────


class QAGenerator:
    """Generate (question, answer, context) triples from text.

    Args:
        vault: The :class:`FakerVault` to use for PII swaps.
            Defaults to the process-wide singleton.
        chunk_size: Characters per chunk window.
        chunk_overlap: Overlap between adjacent windows.
        qa_per_chunk: How many extractive Q/A triples to emit
            per chunk.
        extractive_templates: Custom question templates. The
            generator cycles through them.
    """

    def __init__(
        self,
        *,
        vault: Optional[FakerVault] = None,
        chunk_size: int = DEFAULT_CHUNK_SIZE,
        chunk_overlap: int = DEFAULT_CHUNK_OVERLAP,
        qa_per_chunk: int = DEFAULT_QA_PER_CHUNK,
        extractive_templates: Iterable[str] = EXTRACTIVE_TEMPLATES,
    ) -> None:
        self.vault = vault or get_default_vault()
        self.chunk_size = max(100, int(chunk_size))
        self.chunk_overlap = max(0, min(int(chunk_overlap), self.chunk_size - 1))
        self.qa_per_chunk = max(1, int(qa_per_chunk))
        self.templates = tuple(extractive_templates)

    # ── Public API ───────────────────────────────────────────

    def generate(
        self,
        text: str,
        *,
        source_format: str = "text",
        locale: str = "en",
        qa_type: str = QA_TYPE_EXTRACTIVE,
        tags: Optional[list[str]] = None,
    ) -> list[SyntheticQA]:
        """Generate Q/A triples from ``text``.

        Args:
            text: Raw source. May be plain text, markdown,
                or the contents of a CSV cell (one row per
                ``generate()`` call for CSV).
            source_format: Hint for chunking + provenance.
            locale: Locale of the FakerVault swaps.
            qa_type: ``extractive`` (default), ``abstractive``,
                or ``multi_hop``.
            tags: Free-form tags applied to every triple.

        Returns:
            A list of :class:`SyntheticQA` records. The list
            may be empty if the input is too short.
        """
        if qa_type not in ALL_QA_TYPES:
            raise ValueError(f"unknown qa_type: {qa_type!r}")
        if qa_type == QA_TYPE_ABSTRACTIVE:
            return self._generate_abstractive(
                text, source_format=source_format, locale=locale, tags=tags,
            )
        if qa_type == QA_TYPE_MULTI_HOP:
            return self._generate_multi_hop(
                text, source_format=source_format, locale=locale, tags=tags,
            )
        return self._generate_extractive(
            text, source_format=source_format, locale=locale, tags=tags,
        )

    def generate_from_csv(
        self,
        csv_text: str,
        *,
        text_column: str = "text",
        locale: str = "en",
        qa_type: str = QA_TYPE_EXTRACTIVE,
        tags: Optional[list[str]] = None,
    ) -> list[SyntheticQA]:
        """Parse ``csv_text`` and generate Q/A for every row's
        ``text_column`` value. Returns the concatenated list of
        triples from all rows."""
        if not csv_text.strip():
            return []
        reader = csv.DictReader(io.StringIO(csv_text))
        if text_column not in (reader.fieldnames or []):
            raise ValueError(
                f"csv_text has no {text_column!r} column; "
                f"got columns: {reader.fieldnames}",
            )
        out: list[SyntheticQA] = []
        for row in reader:
            text = row.get(text_column, "")
            if not text:
                continue
            out.extend(self.generate(
                text,
                source_format="csv",
                locale=locale,
                qa_type=qa_type,
                tags=tags,
            ))
        return out

    # ── Internal: extractive ─────────────────────────────────

    def _generate_extractive(
        self,
        text: str,
        *,
        source_format: str,
        locale: str,
        tags: Optional[list[str]],
    ) -> list[SyntheticQA]:
        raw_chunks = chunk_text(
            text,
            chunk_size=self.chunk_size,
            chunk_overlap=self.chunk_overlap,
            source_format=source_format,
        )
        # PII swap (best-effort; the production PII mask is
        # upstream of this call).
        chunks = [
            _pii_swap_chunk(c, vault=self.vault, locale=locale)
            for c in raw_chunks
        ]
        out: list[SyntheticQA] = []
        from datetime import datetime, timezone
        now = datetime.now(timezone.utc).isoformat()
        for chunk in chunks:
            sentences = _split_sentences(chunk.text)
            if not sentences:
                continue
            # Pick up to ``qa_per_chunk`` sentences. We round-
            # robin across the templates so consecutive
            # triples use different phrasings.
            n = min(self.qa_per_chunk, len(sentences))
            for i in range(n):
                sentence = sentences[i]
                topic = _topic_of_sentence(sentence)
                template = self.templates[i % len(self.templates)]
                question = template.format(topic=topic)
                answer = sentence
                qa_id = _qa_id(question, answer, chunk.id)
                out.append(SyntheticQA(
                    id=qa_id,
                    question=question,
                    answer=answer,
                    context=chunk.text[:MAX_CONTEXT_CHARS],
                    source_chunk_id=chunk.id,
                    qa_type=QA_TYPE_EXTRACTIVE,
                    locale=locale,
                    tags=list(tags or []) + ["extractive"],
                    difficulty=1,
                    source_chunks=[chunk.id],
                    metadata={"template_index": i % len(self.templates)},
                    created_at=now,
                ))
        return out

    # ── Internal: abstractive (LLM-driven) ──────────────────

    def _generate_abstractive(
        self,
        text: str,
        *,
        source_format: str,
        locale: str,
        tags: Optional[list[str]],
    ) -> list[SyntheticQA]:
        """Generate abstractive Q/A via the LLM.

        Falls back to extractive when no LLM client is
        configured (the default — production deployments
        inject a real client via the ``llm_client`` kwarg
        on a subclass).
        """
        # The LLM path is a stub here: we don't have an LLM
        # client wired into the unit-testable surface. The
        # production wiring happens in the route layer
        # (``eden.api.routes.qa_generator``) which injects
        # the real client. We DO call out the shape so the
        # subclass is obvious.
        #
        # In a real deployment the prompt is:
        #   "Given the following passage, produce 3
        #   question-answer pairs where the answer is a
        #   paraphrase (not a verbatim copy). Output JSON:
        #   [{\"q\": ..., \"a\": ...}, ...]"
        #
        # And we use the T1 (fast) tier so the cost is bounded.
        return self._generate_extractive(
            text,
            source_format=source_format,
            locale=locale,
            tags=(list(tags or []) + ["abstractive-stub"]),
        )

    # ── Internal: multi-hop ─────────────────────────────────

    def _generate_multi_hop(
        self,
        text: str,
        *,
        source_format: str,
        locale: str,
        tags: Optional[list[str]],
    ) -> list[SyntheticQA]:
        """Compose multi-hop Q/A pairs that require combining
        two adjacent chunks.

        Strategy: take the LAST sentence of chunk N and the
        FIRST sentence of chunk N+1. The answer combines both
        (joined with "and" / "additionally" / etc.). The
        question is templated to require both.

        Multi-hop Q/A is harder than extractive, so the
        difficulty is 4.
        """
        raw_chunks = chunk_text(
            text,
            chunk_size=self.chunk_size,
            chunk_overlap=self.chunk_overlap,
            source_format=source_format,
        )
        chunks = [
            _pii_swap_chunk(c, vault=self.vault, locale=locale)
            for c in raw_chunks
        ]
        out: list[SyntheticQA] = []
        from datetime import datetime, timezone
        now = datetime.now(timezone.utc).isoformat()
        for i in range(len(chunks) - 1):
            left = chunks[i]
            right = chunks[i + 1]
            left_sents = _split_sentences(left.text)
            right_sents = _split_sentences(right.text)
            if not left_sents or not right_sents:
                continue
            # Pick the last sentence of the left + first of
            # the right.
            left_ans = left_sents[-1].rstrip(".")
            right_ans = right_sents[0].rstrip(".")
            combined_answer = f"{left_ans}; additionally, {right_ans}."
            topic = _topic_of_sentence(left_ans + " " + right_ans)
            question = (
                f"Combining the information across two sections, "
                f"describe both {topic}."
            )
            qa_id = _qa_id(question, combined_answer, left.id + right.id)
            out.append(SyntheticQA(
                id=qa_id,
                question=question,
                answer=combined_answer,
                context=(left.text + "\n\n" + right.text)[:MAX_CONTEXT_CHARS],
                source_chunk_id=left.id,
                qa_type=QA_TYPE_MULTI_HOP,
                locale=locale,
                tags=list(tags or []) + ["multi_hop"],
                difficulty=4,
                source_chunks=[left.id, right.id],
                metadata={"composed_from_chunks": [left.id, right.id]},
                created_at=now,
            ))
        return out


# ── Helpers ──────────────────────────────────────────────────────


def _qa_id(question: str, answer: str, source_id: str) -> str:
    """Content-addressed id for a Q/A triple.

    Two triples with the same (question, answer, source)
    get the same id. This makes the output idempotent across
    reruns (e.g. the user clicks "regenerate" and the same
    triples reappear).
    """
    h = hashlib.sha256(
        f"{question}\x00{answer}\x00{source_id}".encode("utf-8"),
    ).hexdigest()[:16]
    return f"qa-{h}"


