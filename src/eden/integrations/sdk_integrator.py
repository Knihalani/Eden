PYTHON_REQUIREMENTS_LINE = "eden-ai>=0.1.0  # added by Eden onboarding\n"
TS_PACKAGE_LINE = '"@eden-ai/sdk": "^0.1.0"  // added by Eden onboarding\n'

# Use a sentinel for the {framework} placeholder so we can use
# str.format_map with a custom formatter that ignores `${VAR}`
# placeholders (those are env-expanded at apply time, not format time).
DEFAULT_EDEN_CONFIG_PY = """\
# Generated by the Eden onboarding wizard. Edit values via the
# portal (Settings → Agents) or by re-running the integration flow.
api_key: ${EDEN_API_KEY}
org_id: ${EDEN_DEFAULT_ORG}
base_url: ${EDEN_BASE_URL:-http://localhost:8000}

autonomy:
  mode: approval
  auto_test: true
  auto_lint: true
  auto_pr: false
  confirm_destructive: true

pr:
  platform: github
  remote: origin
  base_branch: main
  branch_prefix: eden/
  auto_push: true
  draft_by_default: false
  default_reviewers: []
  default_labels: ["eden"]
  commit_prefix: "eden:"

integrate:
  use_server_pipeline: false
  framework: __EDEN_FRAMEWORK__
"""


def _render_eden_config(framework: str) -> str:
    """Render ``DEFAULT_EDEN_CONFIG_PY`` with the framework slot filled.

    Two-pass render:
      1. Replace the ``__EDEN_FRAMEWORK__`` sentinel with the actual
         framework name.
      2. Leave the ``${VAR}`` env-var placeholders alone (the loader
         in :mod:`eden.config` expands those at config-load time).
    """
    return DEFAULT_EDEN_CONFIG_PY.replace("__EDEN_FRAMEWORK__", framework)


PYTHON_INSTRUMENT_TEMPLATE = '''\
# Added by Eden onboarding — Eden auto-instrumentation.
import os
import eden  # type: ignore  # noqa: F401

# Initialise the global tracer. No-op if env vars are not set.
eden.init(
    api_key=os.environ.get("EDEN_API_KEY", ""),
    org_id=os.environ.get("EDEN_DEFAULT_ORG", ""),
    base_url=os.environ.get("EDEN_BASE_URL", "http://localhost:8000"),
    framework={framework_repr},
    auto_instrument=True,
)
'''


TS_INSTRUMENT_TEMPLATE = """\
// Added by Eden onboarding — Eden auto-instrumentation.
import {{ init }} from "@eden-ai/sdk";

init({{
  apiKey: process.env.EDEN_API_KEY ?? "",
  orgId: process.env.EDEN_DEFAULT_ORG ?? "",
  baseUrl: process.env.EDEN_BASE_URL ?? "http://localhost:8000",
  framework: {framework_repr},
  autoInstrument: true,
}});
"""


