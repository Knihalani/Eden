"""SDK integration code generator for the onboarding wizard.

Given a ``FrameworkDetection`` and a target repo, produce the file
changes required to install and auto-instrument the Eden SDK. The
generator is *idempotent* — it never overwrites an existing
``.eden/config.yaml`` and is safe to re-run.

Output is structured as a ``Plan`` of file changes that the calling
flow (the GitHub PR-opener in ``eden.api.routes.github``) commits to a
new branch and opens a pull request against.

Originally lived under ``cli/eden/sdk_integrator.py`` while the agent
CLI shipped. The CLI was retired in the June 2026 cleanup; this
module is now imported by the onboarding wizard.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from eden.integrations.framework_detector import FrameworkDetection


@dataclass
class FileChange:
    """A single proposed file change."""

    path: str  # repo-relative
    operation: str  # "create" | "append" | "modify"
    content: str
    description: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "operation": self.operation,
            "description": self.description,
            "content": self.content,
        }


@dataclass
class IntegrationPlan:
    """A full set of file changes to integrate Eden SDK."""

    framework: str
    language: str
    changes: list[FileChange] = field(default_factory=list)
    dependencies: list[str] = field(default_factory=list)
    install_commands: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "framework": self.framework,
            "language": self.language,
            "dependencies": self.dependencies,
            "install_commands": self.install_commands,
            "notes": self.notes,
            "changes": [c.to_dict() for c in self.changes],
        }


