def _maybe_update_requirements_text(existing: str | None, additions: list[str]) -> FileChange | None:
    """Append to requirements.txt content if present, else create it.

    Pure-text variant for use by the PR-opener flow (which fetches files
    via ``RepoProvider.read_file`` rather than reading from a local
    working tree).
    """
    if existing is not None:
        new_lines = [a for a in additions if a.strip() and a.strip() not in existing]
        if not new_lines:
            return None
        appended = existing.rstrip("\n") + "\n" + "".join(
            "# added by Eden onboarding\n" + a if not a.startswith("#") else a
            for a in new_lines
        )
        return FileChange(
            path="requirements.txt",
            operation="append",
            content=appended,
            description="Append Eden SDK to requirements.txt",
        )
    return FileChange(
        path="requirements.txt",
        operation="create",
        content="# Added by Eden onboarding\n" + "".join(additions),
        description="Create requirements.txt with Eden SDK",
    )


def _maybe_update_package_json_text(existing: str | None, additions: list[str]) -> FileChange | None:
    """Update package.json dependencies block. Conservative: only appends
    packages that are not already present.
    """
    if existing is None:
        return None
    try:
        data = json.loads(existing)
    except json.JSONDecodeError:
        return None
    deps = data.setdefault("dependencies", {})
    changed = False
    for raw in additions:
        # `.rstrip("//")` is a no-op for the trailing-comment case we
        # want to handle (multi-char strip strips characters not
        # substrings); use a single explicit `removesuffix` instead.
        line = raw.strip().rstrip(",").removesuffix("//")
        if not line or line.startswith("//") or line.startswith("#"):
            continue
        # Lines look like: "@eden-ai/sdk": "^0.1.0"
        m = re.match(r'[\'"]?([@a-zA-Z0-9_/\-\.]+)[\'"]?\s*:\s*[\'"]?([^,\'"\n}]+)[\'"]?', line)
        if not m:
            continue
        name, version = m.group(1), m.group(2).strip()
        if name not in deps:
            deps[name] = version
            changed = True
    if not changed:
        return None
    new_content = json.dumps(data, indent=2) + "\n"
    return FileChange(
        path="package.json",
        operation="modify",
        content=new_content,
        description="Add @eden-ai/sdk to package.json dependencies",
    )


def _maybe_update_requirements(repo_root: Path, additions: list[str]) -> FileChange | None:
    """Local-disk variant (kept for backwards-compat with tests)."""
    req = repo_root / "requirements.txt"
    existing = req.read_text(encoding="utf-8") if req.exists() else None
    return _maybe_update_requirements_text(existing, additions)


def _maybe_update_package_json(repo_root: Path, additions: list[str]) -> FileChange | None:
    """Local-disk variant (kept for backwards-compat with tests)."""
    pj = repo_root / "package.json"
    if not pj.exists():
        return None
    return _maybe_update_package_json_text(pj.read_text(encoding="utf-8"), additions)


def _build_python_instrument_file(detection: FrameworkDetection) -> str:
    fw = detection.framework
    imports = PYTHON_IMPORT_SNIPPETS.get(fw, "")
    body = PYTHON_INSTRUMENT_TEMPLATE.format(framework_repr=repr(fw))
    return (
        "# Auto-generated by Eden onboarding — safe to delete if you\n"
        "# prefer to instrument manually.\n"
        f"{imports}{body}"
    )


def _build_ts_instrument_file(detection: FrameworkDetection) -> str:
    fw = detection.framework
    imports = TS_IMPORT_SNIPPETS.get(fw, "")
    body = TS_INSTRUMENT_TEMPLATE.format(framework_repr=f'"{fw}"')
    return (
        "// Auto-generated by Eden onboarding — safe to delete if you\n"
        "// prefer to instrument manually.\n"
        f"{imports}{body}"
    )


def _pick_instrument_path_from_files(files: dict[str, str], language: str) -> str:
    """Choose a path for the new instrument file that doesn't collide
    with an existing module in ``files``. Pure-data variant for the
    PR-opener.
    """
    candidate = "eden_bootstrap.py" if language == "python" else "eden_bootstrap.ts"
    i = 0
    chosen = candidate
    while chosen in files:
        i += 1
        stem = candidate.rsplit(".", 1)[0]
        ext = candidate.rsplit(".", 1)[-1]
        chosen = f"{stem}_{i}.{ext}"
    return chosen


def _pick_instrument_path(repo_root: Path, language: str) -> str:
    """Local-disk variant (kept for backwards-compat with tests)."""
    candidate = "eden_bootstrap.py" if language == "python" else "eden_bootstrap.ts"
    i = 0
    chosen = candidate
    while (repo_root / chosen).exists():
        i += 1
        stem = candidate.rsplit(".", 1)[0]
        ext = candidate.rsplit(".", 1)[-1]
        chosen = f"{stem}_{i}.{ext}"
    return chosen


def build_integration_plan(
    repo_root: str | Path,
    detection: FrameworkDetection,
    *,
    force: bool = False,
) -> IntegrationPlan:
    """Build a ``Plan`` of file changes to integrate Eden SDK against a
    local working tree.

    Used by tests and the legacy local-dev path. The onboarding wizard
    uses :func:`build_integration_plan_from_files` instead, which
    operates purely on an in-memory file map fetched via
    ``RepoProvider``.

    Args:
        repo_root: Path to the user's repo.
        detection: Output of :func:`detect_framework`.
        force: If True, regenerate ``.eden/config.yaml`` even when it exists.
    """
    root = Path(repo_root).expanduser().resolve()
    plan = IntegrationPlan(
        framework=detection.framework,
        language=detection.language,
    )

    if detection.framework == "custom":
        plan.notes.append(
            "No specific framework detected — emitting a generic Eden "
            "auto-instrumentation file. You can refine the imports "
            "manually or re-run after adding framework deps."
        )

    # --- Config ------------------------------------------------------------
    if not (root / ".eden" / "config.yaml").exists() or force:
        plan.changes.append(
            FileChange(
                path=".eden/config.yaml",
                operation="create",
                content=_render_eden_config(detection.framework),
                description="Create .eden/config.yaml",
            )
        )
    else:
        plan.notes.append(
            ".eden/config.yaml already present; preserving user overrides."
        )

    # --- Dependencies & install commands ----------------------------------
    if detection.language == "python":
        plan.dependencies.append("eden-ai")
        plan.install_commands.append("pip install -e '.[eden]'  # or: pip install eden-ai")
        req_change = _maybe_update_requirements(root, [PYTHON_REQUIREMENTS_LINE])
        if req_change:
            plan.changes.append(req_change)
    elif detection.language == "typescript":
        plan.dependencies.append("@eden-ai/sdk")
        plan.install_commands.append("npm install @eden-ai/sdk  # or: pnpm add @eden-ai/sdk")
        pj_change = _maybe_update_package_json(root, [TS_PACKAGE_LINE])
        if pj_change:
            plan.changes.append(pj_change)
    else:
        plan.notes.append(
            "Could not detect language (no requirements.txt or package.json). "
            "Add the Eden SDK manually."
        )

    # --- Bootstrap instrument file ---------------------------------------
    if detection.language in ("python", "typescript"):
        if detection.language == "python":
            content = _build_python_instrument_file(detection)
        else:
            content = _build_ts_instrument_file(detection)
        rel_path = _pick_instrument_path(root, detection.language)
        plan.changes.append(
            FileChange(
                path=rel_path,
                operation="create",
                content=content,
                description="Auto-generated Eden SDK bootstrap module",
            )
        )

    # --- Notes on existing instrumentation --------------------------------
    if detection.existing_instrumentation:
        plan.notes.append(
            "Detected existing instrumentation: "
            + ", ".join(detection.existing_instrumentation)
            + ". Eden runs alongside these by default — no removal required."
        )

    return plan


def build_integration_plan_from_files(
    files: dict[str, str],
    detection: FrameworkDetection,
    *,
    force: bool = False,
) -> IntegrationPlan:
    """Build an integration plan from an in-memory file map.

    Used by the onboarding wizard's PR-opener — fetches the handful of
    manifest files via ``RepoProvider.read_file``, builds the plan, then
    commits the resulting file changes via ``PRProvider.commit_files``.
    No working tree needed; no clone required.

    Args:
        files: Mapping of repo-relative path -> file content (only
            include the manifest files: requirements.txt, pyproject.toml,
            package.json, and any existing ``.eden/config.yaml``).
        detection: Output of :func:`detect_framework_from_files`.
        force: If True, regenerate ``.eden/config.yaml`` even when present.
    """
    plan = IntegrationPlan(
        framework=detection.framework,
        language=detection.language,
    )

    if detection.framework == "custom":
        plan.notes.append(
            "No specific framework detected — emitting a generic Eden "
            "auto-instrumentation file. Edit the imports in the PR if "
            "you want to wire a specific instrumentor."
        )

    # --- Config -----------------------------------------------------------
    eden_cfg = files.get(".eden/config.yaml")
    if eden_cfg is None or force:
        plan.changes.append(
            FileChange(
                path=".eden/config.yaml",
                operation="create",
                content=_render_eden_config(detection.framework),
                description="Create .eden/config.yaml",
            )
        )
    else:
        plan.notes.append(
            ".eden/config.yaml already present; preserving user overrides."
        )

    # --- Dependencies -----------------------------------------------------
    if detection.language == "python":
        plan.dependencies.append("eden-ai")
        plan.install_commands.append("pip install eden-ai")
        req_change = _maybe_update_requirements_text(
            files.get("requirements.txt"), [PYTHON_REQUIREMENTS_LINE]
        )
        if req_change:
            plan.changes.append(req_change)
    elif detection.language == "typescript":
        plan.dependencies.append("@eden-ai/sdk")
        plan.install_commands.append("npm install @eden-ai/sdk")
        pj_change = _maybe_update_package_json_text(
            files.get("package.json"), [TS_PACKAGE_LINE]
        )
        if pj_change:
            plan.changes.append(pj_change)
    else:
        plan.notes.append(
            "Could not detect language (no requirements.txt or package.json). "
            "Add the Eden SDK manually."
        )

    # --- Bootstrap instrument file ---------------------------------------
    if detection.language in ("python", "typescript"):
        if detection.language == "python":
            content = _build_python_instrument_file(detection)
        else:
            content = _build_ts_instrument_file(detection)
        rel_path = _pick_instrument_path_from_files(files, detection.language)
        plan.changes.append(
            FileChange(
                path=rel_path,
                operation="create",
                content=content,
                description="Auto-generated Eden SDK bootstrap module",
            )
        )

    if detection.existing_instrumentation:
        plan.notes.append(
            "Detected existing instrumentation: "
            + ", ".join(detection.existing_instrumentation)
            + ". Eden runs alongside these by default — no removal required."
        )

    return plan


def apply_plan(
    repo_root: str | Path,
    plan: IntegrationPlan,
    *,
    only: list[str] | None = None,
) -> list[str]:
    """Write a plan to disk. Returns the list of paths actually written.

    Args:
        repo_root: Target repo root.
        plan: The plan to apply.
        only: Optional list of relative paths to limit application to.
    """
    root = Path(repo_root).expanduser().resolve()
    written: list[str] = []
    for change in plan.changes:
        if only and change.path not in only:
            continue
        target = root / change.path
        target.parent.mkdir(parents=True, exist_ok=True)
        if change.operation == "append" and target.exists():
            existing = target.read_text(encoding="utf-8")
            if change.content.strip() in existing:
                continue
            new = existing.rstrip("\n") + "\n" + change.content
        else:
            new = change.content
        target.write_text(new, encoding="utf-8")
        written.append(change.path)
    return written


