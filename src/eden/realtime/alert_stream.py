"""Real-time alert generation stream with severity-based routing.

Phase 6.2: Processes events from Kafka/Redis and generates alerts with
severity-based routing to WebSocket, in-app notifications, email, and
webhook channels. Supports custom alert rules and rolling window metrics.

Usage:
    from eden.realtime.alert_stream import AlertStreamProcessor
    processor = AlertStreamProcessor()
    await processor.process_event(event)
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import logging
import uuid
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import StrEnum
from typing import Any

from eden.config import get_settings

logger = logging.getLogger(__name__)
settings = get_settings()


class AlertSeverity(StrEnum):
    """Alert severity levels."""

    DEBUG = "debug"
    INFO = "info"
    WARNING = "warning"
    HIGH = "high"
    CRITICAL = "critical"


class AlertChannel(StrEnum):
    """Alert dispatch channels."""

    IN_APP = "in_app"
    WEBSOCKET = "websocket"
    EMAIL = "email"
    WEBHOOK = "webhook"
    PAGERDUTY = "pagerduty"


@dataclass
class AlertRule:
    """A rule that matches events and generates alerts."""

    rule_id: str
    name: str
    description: str
    # Match conditions
    event_types: list[str] = field(default_factory=list)
    severity_threshold: AlertSeverity = AlertSeverity.WARNING
    metric_threshold: float | None = None
    metric_name: str | None = None
    window_seconds: int = 300  # 5 min default window
    # Actions
    channels: list[AlertChannel] = field(default_factory=lambda: [AlertChannel.IN_APP])
    auto_escalate: bool = False
    escalation_delay_seconds: int = 300
    # Metadata
    enabled: bool = True
    created_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())

    def matches(self, event: dict[str, Any], context: dict[str, Any]) -> bool:
        """Check if this rule matches the given event."""
        if not self.enabled:
            return False

        # Event type match
        event_type = event.get("event_type", "")
        if self.event_types and event_type not in self.event_types:
            return False

        # Metric threshold match
        if self.metric_name and self.metric_threshold is not None:
            value = context.get(self.metric_name)
            if value is None:
                value = event.get("payload", {}).get(self.metric_name)
            if value is not None and isinstance(value, (int, float)):
                if value < self.metric_threshold:
                    return False

        return True


@dataclass
class GeneratedAlert:
    """An alert generated by the stream processor."""

    alert_id: str
    rule_id: str
    severity: AlertSeverity
    title: str
    message: str
    entity_id: str
    tenant_id: str
    channels: list[AlertChannel]
    context: dict[str, Any] = field(default_factory=dict)
    timestamp: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    acknowledged: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {
            "alert_id": self.alert_id,
            "rule_id": self.rule_id,
            "severity": self.severity.value,
            "title": self.title,
            "message": self.message,
            "entity_id": self.entity_id,
            "tenant_id": self.tenant_id,
            "channels": [c.value for c in self.channels],
            "context": self.context,
            "timestamp": self.timestamp,
            "acknowledged": self.acknowledged,
        }


class AlertStreamProcessor:
    """Processes events and generates alerts with severity-based routing.

    Features:
    - Default alert rules for common scenarios (cost spikes, failures, etc.)
    - Custom rules loaded from configuration
    - Rolling window metrics for rate-based alerts
    - Severity-based channel routing
    - Deduplication within configurable time windows
    """

    # Default rules built into the system
    DEFAULT_RULES: list[AlertRule] = [
        AlertRule(
            rule_id="rule_pipeline_failure",
            name="Pipeline Failure",
            description="Alert when a pipeline job fails",
            event_types=["pipeline.job_failed", "job.failed"],
            severity_threshold=AlertSeverity.WARNING,
            channels=[AlertChannel.IN_APP, AlertChannel.WEBSOCKET],
        ),
        AlertRule(
            rule_id="rule_cost_spike",
            name="Cost Spike",
            description="Alert when daily cost exceeds 3x average",
            event_types=["metering.cost_report"],
            severity_threshold=AlertSeverity.HIGH,
            metric_name="daily_cost_usd",
            metric_threshold=100.0,
            channels=[AlertChannel.IN_APP, AlertChannel.WEBSOCKET, AlertChannel.WEBHOOK],
            auto_escalate=True,
        ),
        AlertRule(
            rule_id="rule_hilt_waiting",
            name="Human Approval Required",
            description="Alert when pipeline waits for human approval",
            event_types=["hilt.state_change"],
            severity_threshold=AlertSeverity.INFO,
            channels=[AlertChannel.IN_APP, AlertChannel.WEBSOCKET],
        ),
        AlertRule(
            rule_id="rule_trace_error",
            name="Trace Error",
            description="Alert on significant trace errors",
            event_types=["trace_event", "agent.error"],
            severity_threshold=AlertSeverity.WARNING,
            channels=[AlertChannel.IN_APP, AlertChannel.WEBSOCKET],
        ),
        AlertRule(
            rule_id="rule_sandbox_escape",
            name="Sandbox Security Alert",
            description="Critical alert for sandbox escape attempts",
            event_types=["sandbox.security_alert"],
            severity_threshold=AlertSeverity.CRITICAL,
            channels=[AlertChannel.IN_APP, AlertChannel.WEBSOCKET, AlertChannel.PAGERDUTY, AlertChannel.WEBHOOK],
        ),
    ]

    def __init__(self) -> None:
        self._rules: list[AlertRule] = list(self.DEFAULT_RULES)
        self._metrics_window: dict[str, list[tuple[str, float]]] = {}  # metric -> [(timestamp, value)]
        self._dedup_window: dict[str, datetime] = {}  # dedup_key -> last_alert_time
        self._dedup_ttl_seconds = 300  # 5 minutes
        self._lock = asyncio.Lock()

    async def process_event(self, event: dict[str, Any]) -> list[GeneratedAlert]:
        """Process a single event through all matching alert rules.

        Args:
            event: A dict with at least event_type, entity_id, tenant_id, payload.

        Returns:
            List of generated alerts.
        """
        alerts: list[GeneratedAlert] = []

        # Build context with rolling metrics
        context = await self._build_context(event)

        for rule in self._rules:
            if rule.matches(event, context):
                alert = await self._generate_alert(rule, event, context)
                if alert and await self._should_dispatch(alert):
                    alerts.append(alert)
                    await self._dispatch_alert(alert)

        return alerts

    async def process_batch(self, events: list[dict[str, Any]]) -> list[GeneratedAlert]:
        """Process a batch of events."""
        all_alerts: list[GeneratedAlert] = []
        for event in events:
            alerts = await self.process_event(event)
            all_alerts.extend(alerts)
        return all_alerts

    async def _build_context(self, event: dict[str, Any]) -> dict[str, Any]:
        """Build evaluation context with rolling window metrics."""
        context = dict(event.get("payload", {}))
        context["event_type"] = event.get("event_type", "")
        context["timestamp"] = event.get("timestamp", datetime.now(UTC).isoformat())

        # Add rolling metric context if metric data is present
        metric_name = event.get("payload", {}).get("metric_name")
        if metric_name and metric_name in self._metrics_window:
            values = [v for _, v in self._metrics_window[metric_name][-10:]]
            if values:
                import statistics
                context[f"{metric_name}_avg"] = statistics.mean(values)
                if len(values) > 1:
                    context[f"{metric_name}_std"] = statistics.stdev(values)

        return context

    async def _generate_alert(
        self,
        rule: AlertRule,
        event: dict[str, Any],
        context: dict[str, Any],
    ) -> GeneratedAlert | None:
        """Generate an alert from a matching rule and event."""
        event_type = event.get("event_type", "unknown")
        entity_id = event.get("entity_id", "unknown")
        tenant_id = event.get("tenant_id", "")

        # Determine severity based on event payload
        severity = rule.severity_threshold
        payload_severity = event.get("payload", {}).get("severity")
        if payload_severity:
            with contextlib.suppress(ValueError):
                severity = AlertSeverity(payload_severity)

        # Build title and message
        if "failure" in event_type or "error" in event_type:
            title = f"{rule.name}: {entity_id}"
            message = event.get("payload", {}).get("message", f"{rule.description} detected")
        elif "cost" in event_type:
            cost = context.get("daily_cost_usd", "unknown")
            title = f"Cost Alert: ${cost}"
            message = f"Daily cost is {context.get('cost_multiplier', 'elevated')}x average"
        elif "hilt" in event_type:
            event.get("payload", {}).get("state", {})
            title = "Human Approval Required"
            message = f"Pipeline {entity_id} is waiting for approval"
        else:
            title = rule.name
            message = rule.description

        return GeneratedAlert(
            alert_id=str(uuid.uuid4()),
            rule_id=rule.rule_id,
            severity=severity,
            title=title,
            message=message,
            entity_id=entity_id,
            tenant_id=tenant_id,
            channels=list(rule.channels),
            context={"rule": rule.name, "event_type": event_type, **context},
        )

    async def _should_dispatch(self, alert: GeneratedAlert) -> bool:
        """Check deduplication window to prevent alert spam."""
        async with self._lock:
            now = datetime.now(UTC)
            # Cleanup expired dedup entries to prevent unbounded growth
            expired = [
                k for k, t in self._dedup_window.items()
                if (now - t).total_seconds() > self._dedup_ttl_seconds * 2
            ]
            for k in expired:
                del self._dedup_window[k]

            dedup_key = f"{alert.rule_id}:{alert.entity_id}:{alert.severity.value}"
            last_time = self._dedup_window.get(dedup_key)

            if last_time:
                elapsed = (now - last_time).total_seconds()
                if elapsed < self._dedup_ttl_seconds:
                    logger.debug(f"Alert deduplicated: {dedup_key}")
                    return False

            self._dedup_window[dedup_key] = now
            return True

    async def _dispatch_alert(self, alert: GeneratedAlert) -> None:
        """Dispatch alert to all configured channels."""
        for channel in alert.channels:
            try:
                if channel == AlertChannel.IN_APP:
                    await self._dispatch_in_app(alert)
                elif channel == AlertChannel.WEBSOCKET:
                    await self._dispatch_websocket(alert)
                elif channel == AlertChannel.EMAIL:
                    await self._dispatch_email(alert)
                elif channel == AlertChannel.WEBHOOK:
                    await self._dispatch_webhook(alert)
                elif channel == AlertChannel.PAGERDUTY:
                    await self._dispatch_pagerduty(alert)
            except Exception as exc:
                logger.warning(f"Alert dispatch to {channel.value} failed: {exc}")

    async def _dispatch_in_app(self, alert: GeneratedAlert) -> None:
        """Create in-app notifications for each org member."""
        try:
            from eden.api.deps import resolve_eden_org_id
            from eden.storage.postgres import get_postgres_client

            client = await get_postgres_client()
            if not client:
                return

            org_id = await resolve_eden_org_id(alert.tenant_id) if alert.tenant_id else None
            if not org_id:
                logger.debug("Skipping in-app alert dispatch — no org_id for tenant %s", alert.tenant_id)
                return

            members = await client.fetch(
                "SELECT user_id FROM org_members WHERE org_id = $1",
                org_id,
            )
            if not members:
                return

            payload = {
                "is_alert": True,
                "severity": alert.severity.value,
                "entity_id": alert.entity_id,
                "rule_id": alert.rule_id,
                "channels": [c.value for c in alert.channels],
                **alert.context,
            }

            for member in members:
                notif_id = str(uuid.uuid4())
                await client.execute(
                    """
                    INSERT INTO notifications (id, user_id, org_id, type, title, body, data, created_at)
                    VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
                    """,
                    notif_id,
                    str(member["user_id"]),
                    org_id,
                    f"alert:{alert.severity.value}",
                    alert.title,
                    alert.message,
                    json.dumps(payload),
                    alert.timestamp,
                )
        except Exception as exc:
            logger.warning(f"In-app alert dispatch failed: {exc}")

    async def _dispatch_websocket(self, alert: GeneratedAlert) -> None:
        """Push alert to connected WebSocket clients for the entity."""
        try:
            from eden.api.routes.websocket import _job_connections
            if alert.entity_id in _job_connections:
                message = {
                    "type": "alert",
                    "alert": alert.to_dict(),
                }
                for ws in list(_job_connections[alert.entity_id]):
                    try:
                        await ws.send_json(message)
                    except Exception:
                        _job_connections[alert.entity_id].discard(ws)
                        if not _job_connections[alert.entity_id]:
                            del _job_connections[alert.entity_id]
                            break
        except Exception as exc:
            logger.debug(f"WebSocket alert dispatch failed: {exc}")

    async def _dispatch_email(self, alert: GeneratedAlert) -> None:
        """Sparse email via SendKit (alerts@) — best-effort, rate-limited upstream."""
        try:
            from eden.services.alert_email import send_issue_alert_email

            await send_issue_alert_email(
                org_id=str(alert.tenant_id),
                event_kind="realtime_alert",
                issue_id=getattr(alert, "entity_id", None),
                severity=str(getattr(alert, "severity", "P1") or "P1"),
                title=str(alert.title),
                detail=str(getattr(alert, "message", "") or ""),
            )
        except Exception as exc:  # noqa: BLE001
            logger.debug("Email alert dispatch failed: %s", exc)

    async def _dispatch_webhook(self, alert: GeneratedAlert) -> None:
        """Send alert to configured webhook URL."""
        webhook_url = getattr(settings, "alert_webhook_url", None)
        if not webhook_url:
            return

        try:
            import aiohttp
            async with aiohttp.ClientSession() as session:
                await session.post(
                    webhook_url,
                    json=alert.to_dict(),
                    timeout=aiohttp.ClientTimeout(total=10),
                )
        except Exception as exc:
            logger.warning(f"Webhook alert dispatch failed: {exc}")

    async def _dispatch_pagerduty(self, alert: GeneratedAlert) -> None:
        """Send alert to PagerDuty — gated when PagerDuty is not configured."""
        logger.info("PagerDuty alert skipped:not_configured: %s", alert.title)

    def add_rule(self, rule: AlertRule) -> None:
        """Add a custom alert rule."""
        self._rules.append(rule)

    def remove_rule(self, rule_id: str) -> bool:
        """Remove a rule by ID."""
        original_len = len(self._rules)
        self._rules = [r for r in self._rules if r.rule_id != rule_id]
        return len(self._rules) < original_len

    def get_rules(self) -> list[AlertRule]:
        """List all active rules."""
        return [r for r in self._rules if r.enabled]

    async def acknowledge_alert(self, alert_id: str) -> bool:
        """Mark an alert as acknowledged."""
        # In a real implementation, this would update the alert in the database
        logger.info(f"Alert {alert_id} acknowledged")
        return True


# ── Singleton accessor ──────────────────────────────────────────────────

_alert_processor: AlertStreamProcessor | None = None


async def get_alert_processor() -> AlertStreamProcessor:
    """Get the singleton alert stream processor."""
    global _alert_processor
    if _alert_processor is None:
        _alert_processor = AlertStreamProcessor()
    return _alert_processor


async def close_alert_processor() -> None:
    """Close the alert stream processor."""
    global _alert_processor
    _alert_processor = None
