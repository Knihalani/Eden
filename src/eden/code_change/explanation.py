"""PRExplanationService — the 4-paragraph human-readable explanation.

Every patch in the PR Inbox has a 4-paragraph explanation:

1. **What happened** — the trace + the user-visible symptom, in
   plain English.
2. **Why it happened** — the RCA + the linked source code
   (file:line).
3. **What the patch does** — the fix in plain English + the tests
   added + the docstring updates.
4. **What to watch after merge** — the post-merge monitor's
   regression thresholds + the predicted cost savings.

The explanation is generated by the same larger model, with the
RCA + patch as context. The 4-paragraph format is enforced in the
prompt. The explanation is stored on the ``proposed_patches`` row.

STUB mode returns a templated 4-paragraph explanation derived
from the patch metadata. The real Gate-4a implementation will
call the larger LLM with the v1.4 SLM doing the cheap
read-the-code step.
"""

from __future__ import annotations

import logging
from typing import Any

from ._common import _new_id, _ok_envelope

logger = logging.getLogger(__name__)


class PRExplanationService:
    """The 4-paragraph human-readable explanation for a proposed patch."""

    name = "pr_explanation"

    async def generate(
        self,
        org_id: str,
        patch_id: str,
        rca_summary: str,
        diff_summary: str,
        predicted_cost_savings_usd: float,
    ) -> dict[str, Any]:
        """Return the 4-paragraph explanation.

        STUB: returns a templated 4-paragraph explanation. The
        real Gate-4a implementation will call the larger LLM
        (Claude Sonnet 4.6 default, configurable per-tenant) with
        the v1.4 SLM doing the cheap read-the-code step.
        """
        what_happened = (
            f"The user-visible symptom was reported via a Cat 2 RCA. "
            f"Summary: {rca_summary or '(no RCA summary provided)'}."
        )
        why_it_happened = (
            "The root cause was identified by correlating the Cat 2 "
            "RCA cluster + the Cat 16 Decision path + the affected "
            "telemetry events. The 4-source correlation (stack-trace, "
            "request-path, tool-call lookup, LLM inference) pinpointed "
            "the file:function in the repo."
        )
        what_patch_does = (
            f"The proposed fix is: {diff_summary or '(no diff summary provided)'}. "
            "The patch adds targeted regression tests + updates the "
            "docstring + respects the repo's style profile "
            "(auto-detected from the last 100 merged PRs)."
        )
        what_to_watch = (
            f"The post-merge monitor will watch the affected code path "
            f"at 1h/6h/24h/7d windows and auto-revert on a >10% "
            f"regression (per the policy's ``revert_threshold_pct``). "
            f"Predicted cost savings: "
            f"${predicted_cost_savings_usd:,.0f}/mo."
        )
        return _ok_envelope(
            self.name,
            {
                "patch_id": patch_id,
                "explanation": "\n\n".join(
                    [
                        what_happened,
                        why_it_happened,
                        what_patch_does,
                        what_to_watch,
                    ]
                ),
                "explanation_id": _new_id("expl"),
                "paragraphs": [
                    {"label": "what_happened", "text": what_happened},
                    {"label": "why_it_happened", "text": why_it_happened},
                    {"label": "what_patch_does", "text": what_patch_does},
                    {"label": "what_to_watch", "text": what_to_watch},
                ],
                "message": (
                    "Stub explanation — Gate 4a will call the "
                    "larger LLM with the v1.4 SLM doing the "
                    "read-the-code step."
                ),
            },
        )
