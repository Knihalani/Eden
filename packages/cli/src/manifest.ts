import { createHash } from "node:crypto";
import { existsSync, mkdirSync, unlinkSync } from "node:fs";
import { dirname, join } from "node:path";
import { CLAIMS_LISTING_BANNER, renderClaimsListing } from "@eden/measure";
import { edenHome, ensureHome, readJson, writeFileAtomic } from "./home";

export type ManifestTool = {
  name?: string;
  sequence?: string[];
  id?: string;
  when_to_use?: string;
  read_only?: boolean;
  envelope?: unknown;
  transparent_writes?: boolean;
  rollout?: "canary" | "live";
};

export const SKILL_NAME = "eden-routines";

export const LISTING_WITHHELD_BANNER = CLAIMS_LISTING_BANNER;

const DESC_MAX = 1024;
const NAME_MAX = 64;
const RESERVED = /\b(anthropic|claude)\b/i;
const XML_TAG = /<[^>]+>/;

export function skillPaths(workspace = process.cwd()): { dir: string; skill: string; toolsMd: string } {
  const dir = join(workspace, ".claude", "skills", SKILL_NAME);
  return {
    dir,
    skill: join(dir, "SKILL.md"),
    toolsMd: join(workspace, "eden.tools.md"),
  };
}

export function skillHashLogPath(): string {
  return join(edenHome(), "skill-hash.json");
}

export function listingDraftPath(): string {
  return join(edenHome(), "listing-draft.md");
}

export function renderManifest(tools: ManifestTool[], opts: { runCommand?: string } = {}): string {
  const run = opts.runCommand ?? "eden run <name> --issue <id>";
  const lines: string[] = [
    "<!-- Generated by `eden manifest`. Refresh after approvals; safe to commit. -->",
    "# Eden compiled routines",
    "",
    "These are pre-approved shortcuts this workspace uses repeatedly.",
    "Each replaces a multi-step loop with one call returning the same facts.",
    `Run one: \`${run}\`. Read-only ones are safe; anything else asks first.`,
    "",
  ];
  for (const t of tools) {
    if (!t.name) continue;
    const steps = t.sequence ?? [];
    const ro = t.read_only === true ? "read-only" : "asks-first";
    lines.push(`## ${t.name}`);
    if (t.when_to_use) lines.push(t.when_to_use);
    lines.push(`- replaces: ${steps.join(" → ") || "(recorded routine)"}`);
    lines.push(`- safety: ${ro}`);
    lines.push("- defer_loading: true");
    lines.push("");
  }
  return lines.join("\n");
}

export function renderSkill(tools: ManifestTool[], opts: { runCommand?: string } = {}): string {
  const run = opts.runCommand ?? "eden run <name> --issue <id>";
  const description = skillDescription(tools);
  const lines: string[] = [
    "# Eden compiled routines",
    "",
    `Run one: \`${run}\`. Prefer a named routine over re-running its recorded loop.`,
    "Read-only routines are safe to call; anything else asks first.",
    "",
  ];
  let named = 0;
  for (const t of tools) {
    if (!t.name) continue;
    named += 1;
    const steps = t.sequence ?? [];
    const ro = t.read_only === true ? "read-only" : "asks-first";
    lines.push(`## ${t.name}`);
    if (t.when_to_use) lines.push(t.when_to_use);
    lines.push(`- replaces: ${steps.join(" → ") || "(recorded routine)"}`);
    lines.push(`- safety: ${ro}`);
    lines.push("- defer_loading: true");
    lines.push("");
  }
  if (!named) {
    lines.push("No live routines yet. Approve a compiled program, then drain refreshes this file.");
    lines.push("");
  }
  return `---
name: ${SKILL_NAME}
description: ${description}
---

${lines.join("\n")}`;
}

export function skillDescription(tools: ManifestTool[]): string {
  const names = tools
    .map((t) => t.name)
    .filter((n): n is string => typeof n === "string" && n.length > 0)
    .filter((n) => !RESERVED.test(n) && !XML_TAG.test(n));
  const when = "Applies when a task matches a named routine instead of re-running that loop.";
  if (!names.length) {
    return clipDesc(`Provides pre-approved workspace routines compiled from recorded tool loops. ${when}`);
  }
  const prefix = "Provides pre-approved workspace routines (";
  const tail = `) that replace a multi-step tool loop with one call. ${when}`;
  let listed = "";
  for (let i = 0; i < names.length; i++) {
    const piece = i === 0 ? names[i]! : `, ${names[i]!}`;
    const candidate = `${prefix}${listed}${piece}${tail}`;
    if (candidate.length > DESC_MAX) {
      const ellipsis = `${prefix}${listed}, …${tail}`;
      if (listed && ellipsis.length <= DESC_MAX) return ellipsis;
      break;
    }
    listed += piece;
  }
  return clipDesc(`${prefix}${listed}${tail}`);
}

function clipDesc(s: string): string {
  const clean = s.replace(XML_TAG, "").replace(RESERVED, "").replace(/\s+/g, " ").trim();
  return clean.length <= DESC_MAX ? clean : clean.slice(0, DESC_MAX);
}

export function renderListingDraft(_tools: ManifestTool[]): string {
  const draft = renderClaimsListing();
  return draft.startsWith(LISTING_WITHHELD_BANNER) ? draft : `${LISTING_WITHHELD_BANNER}\n\n${draft}`;
}

export type SkillHashRecord = { path: string; sha256: string; at: string };

export function logSkillHash(path: string, bytes: string): string {
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const rec: SkillHashRecord = { path, sha256, at: new Date().toISOString() };
  try {
    ensureHome();
    writeFileAtomic(skillHashLogPath(), JSON.stringify(rec, null, 2) + "\n");
  } catch {}
  try {
    console.error(`eden skill: ${path} sha256=${sha256}`);
  } catch {}
  return sha256;
}

export function writeSkillBundle(skillPath: string, tools: ManifestTool[]): string {
  mkdirSync(dirname(skillPath), { recursive: true });
  const body = renderSkill(tools);
  writeFileAtomic(skillPath, body);
  const sha256 = logSkillHash(skillPath, body);
  try {
    ensureHome();
    writeFileAtomic(listingDraftPath(), renderListingDraft(tools));
  } catch {}
  dropSkillDirListing(dirname(skillPath));
  return sha256;
}

function dropSkillDirListing(skillDir: string): void {
  try {
    unlinkSync(join(skillDir, "LISTING.md"));
  } catch {}
}

export function refreshOptedInSurfaces(
  tools: ManifestTool[],
  opts: { workspace?: string } = {},
): { skill?: string; toolsMd?: string; sha256?: string } {
  const paths = skillPaths(opts.workspace);
  const out: { skill?: string; toolsMd?: string; sha256?: string } = {};
  if (existsSync(paths.skill)) {
    out.sha256 = writeSkillBundle(paths.skill, tools);
    out.skill = paths.skill;
  }
  if (existsSync(paths.toolsMd)) {
    writeFileAtomic(paths.toolsMd, renderManifest(tools));
    out.toolsMd = paths.toolsMd;
  }
  return out;
}

export function skillFrontmatterOk(md: string): { name: string; description: string } | null {
  if (!md.startsWith("---\n")) return null;
  const end = md.indexOf("\n---\n", 4);
  if (end < 0) return null;
  const fm = md.slice(4, end);
  const name = /^name:\s*(.+)$/m.exec(fm)?.[1]?.trim() ?? "";
  const description = /^description:\s*(.+)$/m.exec(fm)?.[1]?.trim() ?? "";
  if (name !== SKILL_NAME) return null;
  if (name.length < 1 || name.length > NAME_MAX) return null;
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) return null;
  if (description.length < 1 || description.length > DESC_MAX) return null;
  if (XML_TAG.test(name) || XML_TAG.test(description)) return null;
  if (RESERVED.test(name) || RESERVED.test(description)) return null;
  return { name, description };
}

export function manifestCli(args: string[]): void {
  const outIdx = args.indexOf("--out");
  const outArg = outIdx >= 0 ? args[outIdx + 1] : undefined;
  const asSkill = args.includes("--skill");
  const paths = skillPaths();
  const outPath = outArg ?? (asSkill ? paths.skill : paths.toolsMd);
  // Prefer the plane's richer view (when_to_use, read_only) when reachable;
  // fall back to the local cache so this works offline.
  let tools: ManifestTool[] = [];
  const localPath = join(edenHome(), "live-tools.json");
  if (existsSync(localPath)) {
    tools = (readJson<ManifestTool[]>(localPath, []) ?? []) as ManifestTool[];
  }
  if (!Array.isArray(tools) || !tools.length) {
    console.error("eden manifest: no live tools yet — approve something in the workshop first.");
    process.exit(1);
  }
  if (asSkill) {
    writeSkillBundle(outPath, tools);
  } else {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileAtomic(outPath, renderManifest(tools));
  }
  console.log(`wrote ${outPath} (${tools.length} routines${asSkill ? ", skill format" : ""})`);
}
