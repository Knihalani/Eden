import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { edenHome, readJson } from "./home";

/**
 * Filesystem-native tool surface.
 *
 * MCP assumes a client connection and pays schema tokens every turn.
 * Coding agents already read files progressively — a manifest in the repo
 * gives them Eden's programs at ~10–30 tokens per program when relevant and
 * ZERO otherwise, with no transport, no client requirement, and git history
 * for free. This mirrors how AGENTS.md / Skills already work; Eden rides the
 * pattern instead of inventing a transport.
 *
 * The manifest points execution at ONE entry point (`eden run`) rather than
 * advertising schemas; steering and transparent execution remain the primary
 * paths — this file is for the times the agent goes looking on its own.
 */

export type ManifestTool = {
  name?: string;
  sequence?: string[];
  id?: string;
  when_to_use?: string;
  read_only?: boolean;
};

export function renderManifest(tools: ManifestTool[], opts: { runCommand?: string } = {}): string {
  const run = opts.runCommand ?? "eden run <name> --issue <id>";
  const lines: string[] = [
    "<!-- Generated by `eden manifest`. Refresh after approvals; safe to commit. -->",
    "# Eden compiled routines",
    "",
    "These are pre-approved shortcuts this workspace uses repeatedly.",
    "Each replaces a multi-step loop with one call returning the same facts.",
    `Run one: \`${run}\`. Read-only ones are safe; anything else asks first.`,
    "",
  ];
  for (const t of tools) {
    if (!t.name) continue;
    const steps = t.sequence ?? [];
    const ro = t.read_only === true ? "read-only" : "asks-first";
    lines.push(`## ${t.name}`);
    if (t.when_to_use) lines.push(`${t.when_to_use}`);
    lines.push(`- replaces: ${steps.join(" → ") || "(recorded routine)"}`);
    lines.push(`- safety: ${ro}`);
    lines.push("");
  }
  return lines.join("\n");
}

/**
 * Skill-native surface: the SAME content as a SKILL.md bundle.
 *
 * Agent Skills is the cross-agent standard (Claude Code, Codex, Cursor, and
 * dozens more read it), and its progressive-disclosure model is exactly
 * right for us: the frontmatter description is all an agent loads at start,
 * the body only when relevant — so N routines cost ~nothing until used.
 * Prefer emitting this where skills are supported; plain eden.tools.md stays
 * as the fallback for everything else.
 */
export function renderSkill(tools: ManifestTool[], opts: { runCommand?: string } = {}): string {
  const run = opts.runCommand ?? "eden run <name> --issue <id>";
  const names = tools.map((t) => t.name).filter(Boolean);
  const description =
    names.length > 0
      ? `Pre-approved workspace routines (${names.slice(0, 5).join(", ")}${names.length > 5 ? ", …" : ""}) that replace multi-step tool loops with one call. Use when a task matches one instead of re-running the loop.`
      : "Pre-approved workspace routines.";
  const body = renderManifest(tools, opts)
    .replace("<!-- Generated by `eden manifest`. Refresh after approvals; safe to commit. -->\n", "")
    .replace("# Eden compiled routines", "# Eden compiled routines\n\nRun one from the shell:");
  return `---
name: eden-routines
description: ${description}
---

${body}`;
}

export function manifestCli(args: string[]): void {
  const outIdx = args.indexOf("--out");
  const outArg = outIdx >= 0 ? args[outIdx + 1] : undefined;
  const asSkill = args.includes("--skill");
  const defaultPath = asSkill
    ? join(process.cwd(), ".claude", "skills", "eden-routines", "SKILL.md")
    : join(process.cwd(), "eden.tools.md");
  const outPath = outArg ?? defaultPath;
  // Prefer the plane's richer view (when_to_use, read_only) when reachable;
  // fall back to the local cache so this works offline.
  let tools: ManifestTool[] = [];
  const localPath = join(edenHome(), "live-tools.json");
  if (existsSync(localPath)) {
    tools = (readJson<ManifestTool[]>(localPath, []) ?? []) as ManifestTool[];
  }
  if (!tools.length) {
    console.error("eden manifest: no live tools yet — approve something in the workshop first.");
    process.exit(1);
  }
  writeFileSyncSafe(outPath, asSkill ? renderSkill(tools) : renderManifest(tools));
  console.log(`wrote ${outPath} (${tools.length} routines${asSkill ? ", skill format" : ""})`);
}

function writeFileSyncSafe(path: string, content: string): void {
  // Doc file: plain write is fine; no partial-read window matters here.
  const { writeFileSync } = require("node:fs") as typeof import("node:fs");
  writeFileSync(path, content);
}
